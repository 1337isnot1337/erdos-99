#!/usr/bin/env python3
"""Exact finite checks for the annular loaded-endpoint atlas report.

No global-optimality assertion. The report's analytic proof is independent of
these checks. All comparisons use integers or fractions; no tolerance is used.
"""

from fractions import Fraction as F
from itertools import combinations
from math import isqrt


def norm2(p):
    return p[0] ** 2 + p[1] ** 2


def sub(p, q):
    return p[0] - q[0], p[1] - q[1]


def cross(p, q):
    return p[0] * q[1] - p[1] * q[0]


def hull(points):
    points = sorted(set(points))
    if len(points) < 3:
        return points
    lower, upper = [], []
    for target, sequence in ((lower, points), (upper, reversed(points))):
        for p in sequence:
            while len(target) > 1 and cross(
                sub(target[-1], target[-2]), sub(p, target[-1])
            ) <= 0:
                target.pop()
            target.append(p)
    return lower[:-1] + upper[:-1]


def ceiling_sqrt(q):
    q = F(q)
    n = isqrt(q.numerator // q.denominator)
    return n if n * n == q else n + 1


def thin_parabola(n):
    points = [(F(i), F(i * i, n**4)) for i in range(-n, n + 1)]
    assert len(hull(points)) == len(points) == 2 * n + 1
    assert all(abs(y) <= F(1, n * n) for _, y in points)
    diameter_pairs = []
    for i, p in enumerate(points):
        for j, q in enumerate(points[i + 1 :], i + 1):
            distance2 = norm2(sub(p, q))
            assert distance2 >= 1
            assert distance2 <= 4 * n * n
            if distance2 == 4 * n * n:
                diameter_pairs.append((i, j))
    assert diameter_pairs == [(0, 2 * n)]
    center = F(0), F(1, n * n)
    assert all(norm2(sub(p, center)) <= n * n for p in points)
    assert norm2(sub(points[n], center)) < n * n
    return len(points) * (len(points) - 1) // 2


def short_normal_projection(polygon, normal, slope, maximum):
    """Check AA.6 through its stronger exact projected-length bound.

    The rational normal has length one. Coordinates preserve orientation.
    A normal sector centered upwards is encoded by dx<0, |dy|<=a*(-dx).
    """
    nx, ny = normal
    assert nx * nx + ny * ny == 1
    points = [(ny * x - nx * y, nx * x + ny * y) for x, y in polygon]
    radius = F(ceiling_sqrt(max(map(norm2, points))))
    inner2 = min(map(norm2, points))
    h_m = radius * radius - inner2 + F(maximum * maximum, 4)
    projected = F(0)
    sector_indices = []
    for i, p in enumerate(points):
        q = points[(i + 1) % len(points)]
        dx, dy = sub(q, p)
        if dx < 0 and abs(dy) <= slope * (-dx):
            sector_indices.append(i)
            if dx * dx + dy * dy <= maximum * maximum:
                projected -= dx
                # Entire side lies in the widened squared-radius interval:
                # the exact midpoint attains the maximum quadratic correction.
                midpoint = ((p[0] + q[0]) / 2, (p[1] + q[1]) / 2)
                assert norm2(midpoint) >= inner2 - F(maximum * maximum, 4)
    # The sector is a single cyclic chain even when long sides intervene.
    if 0 < len(sector_indices) < len(points):
        selected = set(sector_indices)
        transitions = sum(
            (i in selected) != ((i + 1) % len(points) in selected)
            for i in range(len(points))
        )
        assert transitions == 2
    excess = max(F(0), projected - 2 * radius * slope)
    assert excess * excess <= 4 * h_m, (
        normal, slope, maximum, projected, radius, inner2
    )


def weighted_lattice_vectors():
    # Exact non-square lattice generated by (1,0) and (5/13,12/13).
    # |m*u+n*v|^2=(m+5n/13)^2+(12n/13)^2, so for |n|>=2
    # the length is >1; for n=0,+/-1 the nearest m verifies spacing 1.
    for n in (-1, 0, 1):
        for m in range(-3, 4):
            if (m, n) != (0, 0):
                assert F(m * m) + F(10 * m * n, 13) + n * n >= 1
    counts = []
    for radius in (1, 2, 3, 5, 8, 13):
        bound = 4 * radius
        vectors = [
            F(m * m) + F(10 * m * n, 13) + n * n
            for m in range(-bound, bound + 1)
            for n in range(-bound, bound + 1)
            if (m, n) != (0, 0)
            and F(m * m) + F(10 * m * n, 13) + n * n <= radius * radius
        ]
        # The range contains every eligible vector: |n|<=13R/12 and
        # |m|<=R+5|n|/13<=17R/12.
        assert len(vectors) <= 9 * radius * radius
        # Dyadic upper bounds on 1/|w| avoid evaluating any square roots.
        upper_weight = F(0)
        for length2 in vectors:
            lower = 1
            while (2 * lower) ** 2 <= length2:
                lower *= 2
            upper_weight += F(1, lower)
        # Every dyadic estimate is <2/|w|, so this checks the corresponding
        # doubled AA.7 precursor, not the exact sum of irrational reciprocals.
        assert upper_weight <= 36 * radius
        counts.append((radius, len(vectors)))
    return counts


def diameter_support_sector(polygon, normal, slope, diameter=F(130), support=None):
    """Check DS.0 and the stronger inner-chain argument on exact endpoints.

    Every vertex is on the rational radius-65 circle; its partner is the
    antipodal vertex of the full source. Selected polygons can omit that partner.
    """
    radius = F(65)
    nx, ny = normal
    assert nx * nx + ny * ny == 1
    points = [(ny * x - nx * y, nx * x + ny * y) for x, y in polygon]
    if support is None:
        normals = [(x / radius, y / radius) for x, y in points]
        assert all(norm2(p) == radius * radius for p in points)
    else:
        normals = [
            (ny * support[p][0] - nx * support[p][1],
             nx * support[p][0] + ny * support[p][1])
            for p in polygon
        ]
    for i, p in enumerate(points):
        assert norm2(normals[i]) == 1
        for j, q in enumerate(points):
            d = sub(q, p)
            dn = sub(normals[j], normals[i])
            assert normals[i][0] * d[0] + normals[i][1] * d[1] <= -norm2(d) / (2 * diameter)
            assert dn[0] * d[0] + dn[1] * d[1] >= norm2(d) / diameter
            assert norm2(d) <= diameter * diameter * norm2(dn)
    selected = set()
    for i, p in enumerate(points):
        dx, dy = sub(points[(i + 1) % len(points)], p)
        if dx < 0 and abs(dy) <= slope * (-dx):
            selected.add(i)
    if len(selected) < 3:
        return
    assert len(selected) < len(points)
    starts = [i for i in selected if (i - 1) % len(points) not in selected]
    assert len(starts) == 1
    start = starts[0]
    chain = [(start + i) % len(points) for i in range(len(selected))]
    assert set(chain) == selected
    first, last = (start + 1) % len(points), chain[-1]
    for i in [(start + k) % len(points) for k in range(1, len(selected))]:
        n = normals[i]
        assert n[1] > 0 and abs(n[0]) <= slope * n[1]
    chord = sub(points[last], points[first])
    # |n_j-n_i|<=2 sin(alpha), alpha=atan(slope), squared exactly.
    normal_difference2 = norm2(sub(normals[last], normals[first]))
    assert normal_difference2 * (1 + slope * slope) <= 4 * slope * slope
    assert norm2(chord) * (1 + slope * slope) <= 4 * diameter**2 * slope**2
    projected_inner = sum(
        abs(points[(i + 1) % len(points)][0] - points[i][0])
        for i in chain[1:-1]
    )
    assert projected_inner == abs(chord[0])
    assert projected_inner**2 * (1 + slope * slope) <= 4 * diameter**2 * slope**2


def loaded_chord_checks():
    """Exact adversarial finite checks for GC.1; no global-optimality premise."""
    grid = [(F(x), F(y)) for x in range(3) for y in range(3)]
    source_count = contact_count = choice_count = 0
    for population in range(4, 10):
        for source in combinations(grid, population):
            diameter2 = max(norm2(sub(p, q)) for p, q in combinations(source, 2))
            if diameter2 < 4:
                continue
            partners = {
                p: [q for q in source if norm2(sub(p, q)) == diameter2]
                for p in source
            }
            loaded = [p for p in source if partners[p]]
            polygon = hull(loaded)
            assert len(polygon) == len(loaded)
            hull_edges = {
                frozenset((p, polygon[(i + 1) % len(polygon)]))
                for i, p in enumerate(polygon)
            }
            for p, q in combinations(loaded, 2):
                if norm2(sub(p, q)) != 1:
                    continue
                contact_count += 1
                assert frozenset((p, q)) in hull_edges
                for y in partners[p]:
                    for z in partners[q]:
                        dn = sub(sub(q, z), sub(p, y))
                        d = sub(q, p)
                        assert dn[0] * d[0] + dn[1] * d[1] >= norm2(d)
                        assert norm2(dn) <= F(9, 4) * diameter2
                        choice_count += 1
            source_count += 1
    # GC.R1: an ordinary hull chord, with both endpoints outside diameter support.
    regression = [(F(0), F(0)), (F(1), F(0)), (F(1, 2), F(1)), (F(1, 2), F(-1))]
    polygon = hull(regression)
    assert len(polygon) == 4
    assert min(norm2(sub(p, q)) for p, q in combinations(regression, 2)) == 1
    assert max(norm2(sub(p, q)) for p, q in combinations(regression, 2)) == 4
    assert all(norm2(sub(regression[i], q)) < 4 for i in (0, 1) for q in regression)
    adjacent = {frozenset((p, polygon[(i + 1) % 4])) for i, p in enumerate(polygon)}
    assert frozenset(regression[:2]) not in adjacent
    return source_count, contact_count, choice_count


def main():
    pair_checks = sum(thin_parabola(n) for n in (2, 3, 5, 8, 13, 21, 34))
    base = [(65, 0), (63, 16), (60, 25), (56, 33), (52, 39)]
    circle = sorted(set(
        (F(sx * x), F(sy * y))
        for x, y in base + [(y, x) for x, y in base]
        for sx in (-1, 1) for sy in (-1, 1)
    ))
    circle = hull(circle)
    assert all(norm2(p) == 65**2 for p in circle)
    sparse = hull(circle[::5] + circle[:3])
    jittered = hull([
        (x * F(100 - (i % 3), 100), y * F(100 - (i % 3), 100))
        for i, (x, y) in enumerate(circle)
    ])
    thin = hull([(F(i), F(i * i, 8**4)) for i in range(-8, 9)])
    normals = [(F(1), F(0)), (F(0), F(1)), (F(3, 5), F(4, 5)),
               (F(-5, 13), F(12, 13)), (F(-4, 5), F(-3, 5))]
    slopes = (F(0), F(1, 10), F(1, 4), F(1, 2), F(1))
    maxima = (1, 5, 10, 20, 40, 65, 130)
    normal_checks = 0
    for polygon in (circle, sparse, jittered, thin):
        for normal in normals:
            for slope in slopes:
                for maximum in maxima:
                    short_normal_projection(polygon, normal, slope, maximum)
                    normal_checks += 1
    diameter_checks = 0
    for polygon in (circle, sparse, hull(circle[::3])):
        for normal in normals:
            for slope in slopes:
                diameter_support_sector(polygon, normal, slope)
                diameter_checks += 1
    # Non-Eulerian actual diameter star. The center is a loaded hull vertex,
    # and any one of its three actual partners can supply its outward normal.
    star_source = [(F(0), F(0)), (F(20), F(0)),
                   (F(16), F(12)), (F(240, 13), F(100, 13))]
    star = hull(star_source)
    assert len(star) == 4
    for i, p in enumerate(star_source):
        for q in star_source[i + 1:]:
            assert 1 <= norm2(sub(p, q)) <= 400
    for partner in star_source[1:]:
        support = {p: (p[0] / 20, p[1] / 20) for p in star_source[1:]}
        support[star_source[0]] = -partner[0] / 20, -partner[1] / 20
        for normal in normals:
            for slope in slopes:
                diameter_support_sector(star, normal, slope, F(20), support)
                diameter_checks += 1
    # Rounded constants in AA.8 and AA.3, checked without floating arithmetic.
    assert 240**2 < 62**2 * 15
    assert 120**2 < 31**2 * 15
    assert F(13, 10)**4 > F(8, 3)
    assert F(4, 3)**4 > 3
    assert F(132 * 13, 10) < 172
    assert 480**2 < 124**2 * 15
    assert F(18 * 25, 16) < 29
    assert 48**2 * 2 < 68**2
    assert 96**2 * 2 < 136**2
    print(f"PASS: {pair_checks} exact separation/diameter pairs")
    print("PASS: thin-parabola hull, lattice-distance and minimum-circle certificates")
    print(f"PASS: {normal_checks} exact short-side normal-sector checks")
    print(f"PASS: {diameter_checks} diameter-support normal-cone/inner-chain checks")
    print(f"PASS: lattice-vector counts {weighted_lattice_vectors()}")
    sources, contacts, choices = loaded_chord_checks()
    print(f"PASS: GC.1 on {sources} exact sources, {contacts} loaded unit contacts, {choices} partner choices")
    print("PASS: exact non-endpoint hull-chord regression GC.R1")
    print("PASS: exact rounded-constant checks")
    print("No global optimum or Level I certificate is claimed.")


if __name__ == "__main__":
    main()
