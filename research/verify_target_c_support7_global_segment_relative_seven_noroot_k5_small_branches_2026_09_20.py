#!/usr/bin/env python3
"""Certify three small seven-no-root k=5 Target-C branch closures.

Uses the committed five-no-root k=3 containment theorem, the seven-no-root
all-depth deletion/code bounds, and the exact local geometry from the committed
D=-2,k=4,d=0,p=3 closure.

Closed branches:
  D=-2: (d,p)=(2,0), (1,3)
  D=-1: (d,p)=(2,1)

For D=-2,(d,p)=(1,3), equality in every five-row pair-deletion shadow forces
three singleton incomplete blocks.  The existing local argument forces all
three to be aligned rank-one singletons.  The finite stage below then exhausts
every rank-two coefficient space generated by the remaining empty blocks and
tests the exact generalized-weight requirements (d1,d2)>=(3,4).
"""
from itertools import combinations
from pathlib import Path
import contextlib
import importlib.util
import io

HERE = Path(__file__).resolve().parent
BASE = HERE / "verify_target_c_support7_global_segment_relative_seven_noroot_k4_dminus2_d0p3_closure_2026_09_20.py"
spec = importlib.util.spec_from_file_location("seven_k5_small_base", BASE)
K4 = importlib.util.module_from_spec(spec)
with contextlib.redirect_stdout(io.StringIO()):
    spec.loader.exec_module(K4)
R = K4.R


def five_k3_lower_bound(p, d_virtual, q):
    assert d_virtual >= 1 and 0 <= q <= p
    return 5 + p + 3 * d_virtual - 3 * q


def check_dminus2_d2p0():
    D, k, d, p = -2, 5, 2, 0
    assert 7 + p + 3 * d - 3 * k == D
    # D=-2 depth-two synchronization gives the pair shadow exactly.
    assert (D + 4, k - 2, p) == (2, 3, 0)
    # Five-row k=3 containment has d_virtual>=1 and q=0 when p=0.
    assert five_k3_lower_bound(0, 1, 0) == 8


def check_p3_equality_case():
    cases = []
    for d_virtual in range(1, 8):
        for q in range(4):
            bound = five_k3_lower_bound(3, d_virtual, q)
            if bound <= 2:
                cases.append((d_virtual, q, bound))
    assert cases == [(1, 3, 2)]


def rank2_candidate_spaces(ext, singleton_blocks):
    """All rank-two P generated by empty non-singleton touched blocks."""
    touched = tuple(
        b for b in range(35)
        if any(R.QCOMP[e][b] != (0, 0) for e in ext)
    )
    spaces = {()}
    for b in touched:
        if b in singleton_blocks:
            continue
        empty = K4.local_empty_space(ext, b)
        new = set(spaces)
        for space in spaces:
            joined = K4.union_space(space, empty)
            if len(joined) <= 2:
                new.add(joined)
        spaces = new
    return tuple(space for space in spaces if len(space) == 2)


def satisfies_dminus2_rank2_weights(space):
    """Exact (d1,d2)>=(3,4) test for a rank-two length-seven code."""
    assert len(space) == 2
    # d1>=3: deleting any coordinate pair leaves projection rank two.
    if any(
        len(K4.project_space(space, J)) != 2
        for J in combinations(range(7), 2)
    ):
        return False
    # d2>=4: deleting any three coordinates cannot kill the whole plane.
    if any(
        len(K4.project_space(space, J)) < 1
        for J in combinations(range(7), 3)
    ):
        return False
    return True


def check_dminus2_d1p3():
    D, k, d, p = -2, 5, 1, 3
    assert 7 + p + 3 * d - 3 * k == D
    assert (D + 4, k - 2, p) == (2, 3, 3)
    check_p3_equality_case()

    # Equality forces three singleton blocks.  The analytic local reduction is
    # the same one already proved for the committed k=4,p=3 closure.
    K4.geometry_checks()
    reps = K4.surviving_block_representatives()

    configuration_counts = []
    candidate_counts = []
    survivor_count = 0
    for rep in reps:
        configs = K4.generate_configurations(rep)
        configuration_counts.append(len(configs))
        count = 0
        for ext, _directions in configs:
            spaces = rank2_candidate_spaces(ext, frozenset(rep))
            count += len(spaces)
            survivor_count += sum(
                satisfies_dminus2_rank2_weights(space) for space in spaces
            )
        candidate_counts.append(count)

    assert tuple(configuration_counts) == (654, 81, 54)
    assert sum(configuration_counts) == 789
    assert tuple(candidate_counts) == (19128, 2268, 1386)
    assert sum(candidate_counts) == 22782
    assert survivor_count == 0
    return tuple(configuration_counts), tuple(candidate_counts), survivor_count


def check_dminus1_d2p1():
    D, k, d, p = -1, 5, 2, 1
    assert 7 + p + 3 * d - 3 * k == D

    # A pair with no second quotient-rank drop would give D=3,k=3,p=1,
    # while five-row containment gives D>=6 even at d_virtual=q=1.
    assert (D + 4, k - 2, p) == (3, 3, 1)
    assert five_k3_lower_bound(1, 1, 1) == 6

    # Hence every pair would have to support a nonzero word of rank-two P.
    # d1(P)>=2 makes the words on disjoint pairs {0,1} and {2,3}
    # independent, so they span P inside coordinates {0,1,2,3}.  Then no
    # nonzero P-word can be supported on the disjoint pair {4,5}.
    A = frozenset((0, 1))
    B = frozenset((2, 3))
    C = frozenset((4, 5))
    assert A.isdisjoint(B)
    assert C.isdisjoint(A | B)


def main():
    check_dminus2_d2p0()
    configuration_counts, candidate_counts, survivors = check_dminus2_d1p3()
    check_dminus1_d2p1()

    print("PASS: seven-no-root k=5 small-branch closures")
    print("closed_Dminus2_branches", ((2, 0), (1, 3)))
    print("closed_Dminus1_branches", ((2, 1),))
    print("aligned_configuration_counts", configuration_counts)
    print("seven_cycle_configurations", sum(configuration_counts))
    print("rank2_candidate_counts", candidate_counts)
    print("rank2_coefficient_candidates", sum(candidate_counts))
    print("generalized_weight_survivors", survivors)


if __name__ == "__main__":
    main()
