#!/usr/bin/env python3
"""Exact slack-two containment theorem for the five-no-root k=2 branch.

For t=5,k=2 the global coefficient-constraint space P has rank three.  An
actual state with p<=2 can use at most two singleton incomplete blocks; pairs
have zero local coefficient constraint.  This verifier enumerates every rank-3
P obtainable from local empty constraints plus at most two singleton
constraints, including P that are not generated by empties alone.

For each such P it forms the virtual canonical state that leaves block b empty
iff its empty constraint E_b is contained in P, and completes b otherwise.
Let C be the canonical complete set and H(C) the span of its complete-block T
relations.  The exhaustive scan proves

  * d=|C|-rank H(C) >= 1; and
  * both external null(P) relation rows lie in H(C).

This propagates to every compatible actual state with the same P.  If q
canonical-complete blocks become incomplete, r canonical-empty blocks become
complete, and p counts all selected rows in incomplete blocks, then q<=p and

  delta(A) <= rank H(C)+r = |C|-d+r,
  |A|-3 delta(A) >= 5+p+3d-3q >= 8-2p.

Hence p<=2 has defect at least four.  For p>=3 the crude k=2 bound gives
defect at least p-1>=2.  Therefore every five-no-root k=2 family has defect
at least two.
"""
from argparse import ArgumentParser
from collections import Counter
from pathlib import Path
import contextlib
import importlib.util
import io

HERE = Path(__file__).resolve().parent
BASE = HERE / "verify_target_c_support7_global_segment_relative_five_noroot_k2_2026_09_20.py"
spec = importlib.util.spec_from_file_location("relative_five_noroot_k2_for_slack", BASE)
P0 = importlib.util.module_from_spec(spec)
with contextlib.redirect_stdout(io.StringIO()):
    spec.loader.exec_module(P0)
R = P0.R
K = P0.K
MOD = R.P


def candidate_rank3_spaces_p2(ext, touched):
    """Rank-3 P obtainable using empties and at most two singleton blocks.

    The value attached to each P is the minimum number of singleton blocks
    needed to generate it. At each block exactly one local state is chosen:
    complete contributes no constraint, empty contributes E_b, and a singleton
    contributes its rank-at-most-one local constraint. Pair states also have
    zero constraint, so they create no additional P beyond the complete option.
    """
    best = {(): 0}
    for block in touched:
        empty_key = R.local_constraint_key(ext, block, 0)
        singleton_keys = tuple(sorted({
            key
            for state in (1, 2, 4)
            for key in (R.local_constraint_key(ext, block, state),)
            if key
        }, key=repr))
        new = dict(best)
        for space, singleton_count in best.items():
            joined = R.union_key(space, empty_key)
            if len(joined) <= 3:
                old = new.get(joined)
                if old is None or singleton_count < old:
                    new[joined] = singleton_count

            if singleton_count < 2:
                for key in singleton_keys:
                    joined = R.union_key(space, key)
                    if len(joined) <= 3:
                        old = new.get(joined)
                        if old is None or singleton_count + 1 < old:
                            new[joined] = singleton_count + 1
        best = new

    return tuple(
        (space, singleton_count)
        for space, singleton_count in best.items()
        if len(space) == 3 and singleton_count <= 2
    )


def virtual_canonical(ext, touched, space):
    return tuple(
        0 if R.is_subspace(R.local_constraint_key(ext, block, 0), space) else 7
        for block in touched
    )


def rref_basis_mod(rows):
    basis = {}
    for row in rows:
        v = [int(x) % MOD for x in row]
        for pivot in sorted(basis):
            if v[pivot]:
                q = v[pivot]
                br = basis[pivot]
                v = [(x - q * y) % MOD for x, y in zip(v, br)]
        pivot = next((j for j, x in enumerate(v) if x), None)
        if pivot is None:
            continue
        inv = pow(v[pivot], -1, MOD)
        v = [(x * inv) % MOD for x in v]
        for old_pivot in list(basis):
            if basis[old_pivot][pivot]:
                q = basis[old_pivot][pivot]
                basis[old_pivot] = [
                    (x - q * y) % MOD for x, y in zip(basis[old_pivot], v)
                ]
        basis[pivot] = v
    return tuple((pivot, tuple(basis[pivot])) for pivot in sorted(basis))


def contained_mod(row, basis):
    v = [int(x) % MOD for x in row]
    for pivot, br in basis:
        if v[pivot]:
            q = v[pivot]
            v = [(x - q * y) % MOD for x, y in zip(v, br)]
    return not any(v)


def scan(keys, orbits, start, stop):
    key_to_global = {K.cycle_key(R.DESC[e]): e for e in R.NO_ROOT}
    canonical_count = 0
    min_singleton_census = Counter()
    deficiency_census = Counter()
    basis_cache = {}
    max_external_norm2 = 0
    first_failure = None

    for orbit_index in range(start, stop):
        local_five = orbits[orbit_index]
        ext = tuple(key_to_global[keys[i]] for i in local_five)
        touched = tuple(sorted(
            block
            for block in range(35)
            if any(R.QCOMP[e][block] != (0, 0) for e in ext)
        ))

        for space, min_singletons in candidate_rank3_spaces_p2(ext, touched):
            states = virtual_canonical(ext, touched, space)
            canonical_count += 1
            min_singleton_census[min_singletons] += 1
            complete_set = tuple(
                block for block, state in zip(touched, states) if state == 7
            )

            basis = basis_cache.get(complete_set)
            if basis is None:
                basis = rref_basis_mod([P0.COMPLETE_T[block] for block in complete_set])
                basis_cache[complete_set] = basis
            d = len(complete_set) - len(basis)
            deficiency_census[d] += 1
            if d < 1:
                first_failure = (
                    "deficiency", orbit_index, ext, touched, space,
                    min_singletons, complete_set, len(basis), d,
                )
                break

            rows = P0.relation_rows(ext, touched, states, space)
            external = rows[len(complete_set):]
            assert len(external) == 2
            for row in external:
                max_external_norm2 = max(
                    max_external_norm2, sum(x * x for x in row)
                )
                if not contained_mod(row, basis):
                    first_failure = (
                        "containment", orbit_index, ext, touched, space,
                        min_singletons, complete_set, len(basis), d, row,
                    )
                    break
            if first_failure is not None:
                break
        if first_failure is not None:
            break

    return {
        "canonical_count": canonical_count,
        "min_singleton_census": min_singleton_census,
        "deficiency_census": deficiency_census,
        "basis_cache_size": len(basis_cache),
        "max_external_norm2": max_external_norm2,
        "first_failure": first_failure,
    }


def main():
    parser = ArgumentParser()
    parser.add_argument("--orbit-start", type=int, default=0)
    parser.add_argument("--orbit-end", type=int)
    args = parser.parse_args()

    assert R.lucas_lehmer_127()
    keys, orbits, orbit_sizes, augmentation_candidates = K.five_no_root_orbits()
    end = len(orbits) if args.orbit_end is None else args.orbit_end
    assert 0 <= args.orbit_start <= end <= len(orbits)

    result = scan(keys, orbits, args.orbit_start, end)
    assert result["first_failure"] is None, result["first_failure"]

    max_complete_norm2 = max(sum(x * x for x in row) for row in P0.COMPLETE_T)
    bound_norm2 = max(max_complete_norm2, result["max_external_norm2"])
    assert MOD * MOD > max(1, bound_norm2) ** 15

    if args.orbit_start == 0 and end == len(orbits):
        assert len(orbits) == 20451
        assert sum(orbit_sizes) == 96560646
        assert augmentation_candidates == 20475
        assert result["canonical_count"] == 628708
        assert dict(sorted(result["min_singleton_census"].items())) == {
            0: 263592,
            1: 239520,
            2: 125596,
        }
        assert dict(sorted(result["deficiency_census"].items())) == {
            1: 5210,
            2: 323203,
            3: 230972,
            4: 67106,
            5: 2213,
            6: 4,
        }
        assert result["max_external_norm2"] == 76
        assert max_complete_norm2 == 12

    print("PASS: five-no-root k=2 slack-two containment")
    print("five_no_root_subsets", 96560646)
    print("S7_orbits", len(orbits))
    print("orbit_range", args.orbit_start, end)
    print("virtual_rank3_states", result["canonical_count"])
    print("minimum_singleton_generator_census", dict(sorted(result["min_singleton_census"].items())))
    print("deficiency_census", dict(sorted(result["deficiency_census"].items())))
    print("max_complete_row_norm_squared", max_complete_norm2)
    print("max_external_row_norm_squared", result["max_external_norm2"])
    print("hadamard_exact_rank_bound", MOD * MOD > max(1, bound_norm2) ** 15)
    print("basis_cache_size", result["basis_cache_size"])
    print("consequence", "every five-no-root k=2 family has defect at least 2")


if __name__ == "__main__":
    main()
