#!/usr/bin/env python3
"""Target C opposite-matching contraction audit.

Mathematical question tested
----------------------------
For m opposite diameter pairs on 2m cyclic terminals, let Q be the pair-incidence
matrix, B=diag(beta_i)>0, K=Q^T Lambda^+ Q, and U_i=a_i(1,t_i) with
0=t_0<t_1<...<t_{m-1} and a_i>0.  Circular-planar Kalmanson resistance implies
that K lies in the cone generated by z z^T, where

    z_i = 1_I(i) - 1_I(i+m)

for cyclic intervals I of the 2m terminals.  The C11 affine identity is

    K B U = U.

C51 proves B^{-1}-K >= 0 for m=4.  This script tests the all-m analogue.

What this script proves
-----------------------
The default exact check is a regression against a tempting proof shortcut.  It
constructs an exact rational m=5 Kalmanson-split-cone instance satisfying KBU=U
whose contraction defect is positive semidefinite, but whose transformed
long-range slope coupling

    sum_{i<=2, j>=4} gamma_i gamma_j K_ij

is strictly positive.  Thus a proof cannot simply show that all such cross-cut
couplings are nonpositive and read the defect as a one-dimensional Laplacian.

The optional --scan mode is floating-point computational evidence only.  It uses
SciPy linear programming to sample feasible Kalmanson split-cone instances for
m=4,...,7 and fixed directions in the orthogonal complement of the affine
subspace.  Failure with objective >1 would falsify the contraction conjecture;
passing does not prove it.

Assumptions intentionally omitted
---------------------------------
The abstract audit keeps exactly the ordered opposite-chord direction data used by
C51, the positive beta weights, the Kalmanson split cone, and KBU=U.  It does not
construct a unit-contact network, a global minimum-diameter source, or a planar
polygon realizing every chosen (a_i,t_i).

Arithmetic
----------
The default regression uses fractions.Fraction throughout.  --scan uses NumPy and
SciPy floating point.

Reproduce
---------
    python3 research/target_c_matching_contraction_audit.py
    python3 research/target_c_matching_contraction_audit.py --scan
"""

from __future__ import annotations

import argparse
from fractions import Fraction as F
from typing import Dict, Iterable, List, Sequence, Tuple

Vector = Tuple[int, ...]
Matrix = List[List[F]]


def zeros(n: int, m: int) -> Matrix:
    return [[F(0) for _ in range(m)] for _ in range(n)]


def transpose(a: Matrix) -> Matrix:
    return [list(row) for row in zip(*a)]


def matmul(a: Matrix, b: Matrix) -> Matrix:
    bt = transpose(b)
    return [[sum(x * y for x, y in zip(row, col)) for col in bt] for row in a]


def matsub(a: Matrix, b: Matrix) -> Matrix:
    return [[x - y for x, y in zip(ra, rb)] for ra, rb in zip(a, b)]


def diag(values: Sequence[F]) -> Matrix:
    out = zeros(len(values), len(values))
    for i, x in enumerate(values):
        out[i][i] = x
    return out


def outer(z: Sequence[int]) -> Matrix:
    return [[F(x * y) for y in z] for x in z]


def add_scaled(a: Matrix, b: Matrix, scale: F) -> None:
    for i in range(len(a)):
        for j in range(len(a[0])):
            a[i][j] += scale * b[i][j]


def cyclic_split_vectors(m: int) -> List[Vector]:
    """Return unique opposite-pair interval-difference vectors, up to global sign."""
    n = 2 * m
    seen = set()
    out: List[Vector] = []
    for start in range(n):
        for length in range(1, n):
            interval = {(start + k) % n for k in range(length)}
            z = [int(i in interval) - int(i + m in interval) for i in range(m)]
            if not any(z):
                continue
            first = next(v for v in z if v)
            if first < 0:
                z = [-v for v in z]
            key = tuple(z)
            if key not in seen:
                seen.add(key)
                out.append(key)
    return out


def exact_regression() -> None:
    m = 5
    t = [F(x) for x in (0, 1, 4, 7, 8)]
    a = [F(x) for x in (4, 1, 2, 1, 2)]
    beta = [F(x) for x in (1, 2, 4, 2, 4)]
    gamma = [a[i] * beta[i] for i in range(m)]

    # Exact positive split weights.  Every listed vector is generated by a cyclic
    # interval of the 10-terminal order.
    weights: Dict[Vector, F] = {
        (1, 0, 0, 0, 0): F(43, 55),
        (1, 1, 0, 0, 0): F(483, 48880),
        (1, 1, 1, 0, 0): F(3, 47),
        (0, 0, 1, 1, 1): F(24489, 537680),
        (0, 0, 0, 0, 1): F(11, 80),
        (1, 0, -1, -1, -1): F(1, 110),
        (1, 1, -1, -1, -1): F(457, 97760),
        (1, 1, 1, -1, -1): F(5, 376),
        (1, 1, 1, 1, -1): F(1, 160),
    }
    available = set(cyclic_split_vectors(m))
    assert set(weights) <= available
    assert all(w > 0 for w in weights.values())

    k = zeros(m, m)
    for z, lam in weights.items():
        add_scaled(k, outer(z), lam)

    b = diag(beta)
    u = [[a[i], a[i] * t[i]] for i in range(m)]
    assert matmul(matmul(k, b), u) == u, "exact affine identity KBU=U failed"

    # The tempting slope-Laplacian shortcut would require this rectangular cross
    # sum to be nonpositive.  It is exactly positive.
    cross = sum(gamma[i] * gamma[j] * k[i][j] for i in range(3) for j in range(4, 5))
    assert cross == F(36672, 33605)
    assert cross > 0

    # Nevertheless the contraction defect is PSD.  Certify it exactly via the
    # local affine-annihilator (Gale) factorization E(B-BKB)E = C G C^T.
    e = diag(a)
    n_def = matsub(b, matmul(matmul(b, k), b))
    m_def = matmul(matmul(e, n_def), e)

    c: Matrix = [
        [F(3), F(0), F(0)],
        [F(-4), F(3), F(0)],
        [F(1), F(-6), F(1)],
        [F(0), F(3), F(-4)],
        [F(0), F(0), F(3)],
    ]
    g: Matrix = [
        [F(59767, 302445), F(64033, 362934), F(35824, 302445)],
        [F(64033, 362934), F(3243199, 10888020), F(182368, 907335)],
        [F(35824, 302445), F(182368, 907335), F(72352, 302445)],
    ]
    assert matmul(matmul(c, g), transpose(c)) == m_def

    # Sylvester criterion for G>0.  C has full column rank, so M_def and N_def
    # are PSD with exactly the two affine kernel directions.
    d1 = g[0][0]
    d2 = g[0][0] * g[1][1] - g[0][1] * g[1][0]
    d3 = (
        g[0][0] * (g[1][1] * g[2][2] - g[1][2] * g[2][1])
        - g[0][1] * (g[1][0] * g[2][2] - g[1][2] * g[2][0])
        + g[0][2] * (g[1][0] * g[2][1] - g[1][1] * g[2][0])
    )
    assert d1 == F(59767, 302445) and d1 > 0
    assert d2 == F(29036, 1046925) and d2 > 0
    assert d3 == F(64, 22275) and d3 > 0

    print("exact m=5 regression: PASS")
    print(f"positive forbidden-by-naive-proof cross sum = {cross} ~= {float(cross):.12f}")
    print("defect certificate: E(B-BKB)E = C G C^T with G positive definite")


def floating_scan(seed: int = 20260831) -> None:
    try:
        import numpy as np
        from scipy.optimize import linprog
    except ImportError as exc:  # pragma: no cover - optional research dependency
        raise SystemExit("--scan requires numpy and scipy") from exc

    rng = np.random.default_rng(seed)
    tol = 1e-8
    for m in range(4, 8):
        z = np.array(cyclic_split_vectors(m), dtype=float)
        zz = np.einsum("ki,kj->kij", z, z)
        worst = 0.0
        for _trial in range(4):
            gaps = rng.integers(1, 5, size=m - 1)
            t = np.r_[0.0, np.cumsum(gaps).astype(float)]
            a = rng.integers(1, 5, size=m).astype(float)
            beta = rng.integers(1, 5, size=m).astype(float)
            u = a[:, None] * np.c_[np.ones(m), t]
            bu = beta[:, None] * u

            aeq = np.stack(
                [(zz[:, i, :] @ bu[:, c]) for i in range(m) for c in range(2)]
            )
            beq = u.reshape(-1)
            feasible = linprog(
                rng.normal(size=len(z)), A_eq=aeq, b_eq=beq, bounds=(0, None), method="highs"
            )
            if not feasible.success:
                continue

            d = np.diag(np.sqrt(beta))
            t_mats = np.einsum("ab,kbc,cd->kad", d, zz, d)
            affine = d @ u
            q, _ = np.linalg.qr(affine, mode="complete")
            complement = q[:, 2:]

            for _ in range(120):
                coeff = rng.normal(size=m - 2)
                coeff /= np.linalg.norm(coeff)
                x = complement @ coeff
                objective = -np.einsum("kij,i,j->k", t_mats, x, x)
                res = linprog(
                    objective, A_eq=aeq, b_eq=beq, bounds=(0, None), method="highs"
                )
                if res.status == 3:
                    raise AssertionError(f"unbounded fixed-direction objective at m={m}")
                if res.success:
                    worst = max(worst, -float(res.fun))
                    if worst > 1 + tol:
                        raise AssertionError(
                            f"sampled contraction violation at m={m}: {worst:.12g}"
                        )
        print(f"m={m}: sampled fixed-direction optimum <= {worst:.12f}")

    print("floating scan: no sampled contraction violation (not a proof)")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--scan", action="store_true", help="run optional SciPy LP scan")
    args = parser.parse_args()
    exact_regression()
    if args.scan:
        floating_scan()


if __name__ == "__main__":
    main()
