#!/usr/bin/env python3
"""Exact t=5, k=2, p=0 rank-density barrier for Target C.

Use the relative four-cycle notation from the preceding audits. For five
no-root four-cycles, a possible violation of 3*delta(A) <= |A| has

    (k,p) in {(2,0), (3,p<=3), (4,p<=6), (5,p<=9)}.

This verifier closes the k=2,p=0 branch.

When k=2, the global external coefficient-constraint space has rank 3 in the
five no-root coefficients. Since p=0, every touched root-0 quotient block is
either empty or complete. For a fixed rank-3 constraint space P there is a
canonical least-row state: leave a touched block empty exactly when its local
empty-state constraint is contained in P, and complete it otherwise. If an
actual state realizes P, this canonical state also realizes P. Every other
state with the same P is obtained by completing some redundant empty blocks;
each such completion adds three selected rows and at most one relative T
relation, so |A|-3*delta cannot decrease.

The 96,560,646 five-subsets are reduced to the exact 20,451 S7 orbit
representatives already certified by the k=5 verifier. Exhaustive generation
of every obtainable rank-3 constraint space gives 263,592 canonical states.
Of these, 355 have at least 14 complete blocks and are safe from the ambient
15-dimensional T rank cap. In every remaining state the complete-block T
relations are already linearly dependent. Therefore, after adding the two
possible external-nullspace relations, the defect is still at least 2.

Complete-block ranks are computed modulo P=2^127-1. Lucas-Lehmer plus the
explicit Hadamard bound P^2 > 12^15 makes those rank decisions exact over Q.
"""
from argparse import ArgumentParser
from collections import Counter
from pathlib import Path
import contextlib
import importlib.util
import io

HERE = Path(__file__).resolve().parent
K5 = HERE / "verify_target_c_support7_global_segment_relative_five_noroot_k5_2026_09_20.py"
spec = importlib.util.spec_from_file_location("relative_five_noroot_k5_for_k2", K5)
K = importlib.util.module_from_spec(spec)
with contextlib.redirect_stdout(io.StringIO()):
    spec.loader.exec_module(K)
R = K.R


COMPLETE_T = []
for ids in R.BLOCKS:
    COMPLETE_T.append(tuple(
        R.MCOORD[ids[0]][70 + j]
        - R.MCOORD[ids[1]][70 + j]
        - R.MCOORD[ids[2]][70 + j]
        for j in range(15)
    ))


def candidate_rank3_constraint_spaces(ext, touched):
    """All rank-3 spans generated by local empty-state constraints."""
    spaces = {()}
    for b in touched:
        local = R.local_constraint_key(ext, b, 0)
        new = set(spaces)
        for space in spaces:
            joined = R.union_key(space, local)
            if len(joined) <= 3:
                new.add(joined)
        spaces = new
    return tuple(space for space in spaces if len(space) == 3)


def canonical_minimal_state(ext, touched, space):
    """Least-row empty/complete state realizing one rank-3 constraint space."""
    states = []
    generated = ()
    for b in touched:
        empty_key = R.local_constraint_key(ext, b, 0)
        if R.is_subspace(empty_key, space):
            states.append(0)
            generated = R.union_key(generated, empty_key)
        else:
            states.append(7)
    if generated != space:
        return None
    return tuple(states)


def scan(keys, orbits, start, stop):
    key_to_global = {K.cycle_key(R.DESC[e]): e for e in R.NO_ROOT}
    canonical_states = 0
    dimension_cap_states = 0
    deficiency_census = Counter()
    complete_count_census = Counter()
    complete_rank_census = Counter()
    constraint_space_count = Counter()
    complete_rank_cache = {}
    first_independent = None

    for orbit_index in range(start, stop):
        local_five = orbits[orbit_index]
        ext = tuple(key_to_global[keys[i]] for i in local_five)
        touched = tuple(sorted(
            b for b in range(35)
            if any(R.QCOMP[e][b] != (0, 0) for e in ext)
        ))
        spaces = candidate_rank3_constraint_spaces(ext, touched)
        constraint_space_count[len(spaces)] += 1

        for space in spaces:
            states = canonical_minimal_state(ext, touched, space)
            assert states is not None
            canonical_states += 1
            complete_set = tuple(
                b for b, state in zip(touched, states) if state == 7
            )
            c = len(complete_set)
            complete_count_census[c] += 1

            if c > 13:
                dimension_cap_states += 1
                continue

            rank = complete_rank_cache.get(complete_set)
            if rank is None:
                rank = R.rank_mod([COMPLETE_T[b] for b in complete_set])
                complete_rank_cache[complete_set] = rank
            complete_rank_census[(c, rank)] += 1
            deficiency = c - rank
            deficiency_census[deficiency] += 1
            if deficiency <= 0:
                first_independent = (
                    orbit_index,
                    ext,
                    touched,
                    space,
                    states,
                    complete_set,
                    rank,
                )
                return {
                    "canonical_states": canonical_states,
                    "dimension_cap_states": dimension_cap_states,
                    "deficiency_census": deficiency_census,
                    "complete_count_census": complete_count_census,
                    "complete_rank_census": complete_rank_census,
                    "constraint_space_count": constraint_space_count,
                    "complete_rank_cache_size": len(complete_rank_cache),
                    "first_independent": first_independent,
                }

    return {
        "canonical_states": canonical_states,
        "dimension_cap_states": dimension_cap_states,
        "deficiency_census": deficiency_census,
        "complete_count_census": complete_count_census,
        "complete_rank_census": complete_rank_census,
        "constraint_space_count": constraint_space_count,
        "complete_rank_cache_size": len(complete_rank_cache),
        "first_independent": None,
    }


def main():
    parser = ArgumentParser()
    parser.add_argument("--orbit-start", type=int, default=0)
    parser.add_argument("--orbit-end", type=int)
    args = parser.parse_args()

    assert R.lucas_lehmer_127()
    keys, orbits, orbit_sizes, augmentation_candidates = K.five_no_root_orbits()
    end = len(orbits) if args.orbit_end is None else args.orbit_end
    assert 0 <= args.orbit_start <= end <= len(orbits)

    result = scan(keys, orbits, args.orbit_start, end)
    assert result["first_independent"] is None, result["first_independent"]

    max_complete_norm2 = max(sum(x * x for x in row) for row in COMPLETE_T)
    assert max_complete_norm2 == 12
    assert R.P * R.P > max_complete_norm2 ** 15

