#!/usr/bin/env python3
"""Actual-state realization audit for eight-no-root k=6 Profile A.

This strengthens the fixed-eight-class Profile A global lift audit. A genuine
Profile A state has seven singleton replacement blocks and one pair replacement
block. The eight replacement classes form a basis of the eight-dimensional
replacement-functional quotient, but they must also realize the prescribed
rank-two coefficient plane.

Pair states have local span kind 2, hence impose no coefficient constraint.
Thus the coefficient plane is generated only by the virtual-empty blocks and
the seven singleton replacement constraints. Because the target coefficient
space has rank two, any actual basis contains an independent singleton seed of
size at most two that already completes the empty-block constraint span to the
full plane.

For a fixed pair block/state this wrapper first applies the resulting mixed
coefficient-functional seed lemma. It then monkeypatches the exact global rank
test so that every chosen seven-singleton-plus-pair basis must generate exactly
the prescribed coefficient plane. Any source candidate that reaches functional
rank eight is independently reconstructed as an actual root-block state and is
required to have exact rational defect -1.
"""

from collections import Counter
from itertools import combinations
from pathlib import Path
import contextlib
import importlib.util
import io

HERE = Path(__file__).resolve().parent
BASE = HERE / "verify_target_c_support7_global_segment_relative_eight_noroot_k6_dminus1_profile_a_global_fixed_basis_2026_09_22.py"
spec = importlib.util.spec_from_file_location("e99_profile_a_global_fixed_basis", BASE)
A = importlib.util.module_from_spec(spec)
with contextlib.redirect_stdout(io.StringIO()):
    spec.loader.exec_module(A)

A0 = A.A0
S = A.S
G = A.G
R = A.R

ORIG_FIXED_GLOBAL_BASIS_EXISTS = A.fixed_global_basis_exists
ORIG_FIXED_EXTRA_RANK = A.fixed_extra_rank

ACTUAL_A_COUNTS = Counter()
ACTUAL_A_EXAMPLES = []


def actual_space(ext, touched, states):
    """Exact coefficient space generated by the specified actual block states."""
    space = ()
    for block, state in zip(touched, states):
        space = R.union_key(space, R.local_constraint_key(ext, block, state))
        if len(space) > 2:
            return space
    return space


def source_data(ext8, space8, pair_block, pair_state, rank_cache):
    """Return source quotient data for the mixed Profile A seed test."""
    state8 = A.canonical_state(ext8, space8, rank_cache)
    if state8 is None:
        return None
    complete, d8, _rows, canonical, base_rank = state8
    if d8 != 2 or pair_block not in complete:
        return None
    if pair_state not in (3, 5, 6):
        return None
    if R.local_constraint_key(ext8, pair_block, pair_state):
        return None

    touched = S.touched_blocks(ext8)
    virtual_states = G.virtual_canonical(ext8, touched, space8)
    complete_index = {block: i for i, block in enumerate(complete)}

    singleton_state = {}
    singleton_vector = {}
    singleton_constraint = {}
    for block in complete:
        if block == pair_block:
            continue
        options = A0.singleton_options(ext8, block, space8)
        if not options:
            continue
        assert len(options) == 1
        state = options[0]
        constraint = R.local_constraint_key(ext8, block, state)
        assert len(constraint) <= 1
        assert R.is_subspace(constraint, space8)
        singleton_state[block] = state
        singleton_constraint[block] = constraint
        singleton_vector[block] = A.replacement_functional(
            ext8, block, state, space8, complete_index, len(complete)
        )

    pair_vector = A.replacement_functional(
        ext8, pair_block, pair_state, space8, complete_index, len(complete)
    )

    empty_space = ()
    for block, state in zip(touched, virtual_states):
        if state != 0:
            continue
        empty_space = R.union_key(
            empty_space, R.local_constraint_key(ext8, block, 0)
        )
    assert R.is_subspace(empty_space, space8)

    return {
        "touched": touched,
        "virtual_states": virtual_states,
        "canonical": canonical,
        "base_rank": base_rank,
        "singleton_state": singleton_state,
        "singleton_vector": singleton_vector,
        "singleton_constraint": singleton_constraint,
        "pair_vector": pair_vector,
        "empty_space": empty_space,
    }


def mixed_extra_rank(data, singleton_blocks):
    vectors = [data["pair_vector"]]
    vectors.extend(data["singleton_vector"][b] for b in singleton_blocks)
    return A.rank_q(data["canonical"] + vectors) - data["base_rank"]


def mixed_seed_exists(ext8, space8, pair_block, pair_state, rank_cache):
    data = source_data(ext8, space8, pair_block, pair_state, rank_cache)
    if data is None:
        return False
    good = tuple(data["singleton_vector"])
    if len(good) < 7 or mixed_extra_rank(data, good) != 8:
        return False

    E = data["empty_space"]
    ACTUAL_A_COUNTS[("empty_constraint_rank", len(E))] += 1
    ACTUAL_A_COUNTS[("source_singleton_capacity_excluding_pair", len(good))] += 1
    for size in range(3):
        for seed in combinations(good, size):
            coeff = E
            for block in seed:
                coeff = R.union_key(coeff, data["singleton_constraint"][block])
            if coeff == space8 and mixed_extra_rank(data, seed) == 1 + size:
                ACTUAL_A_COUNTS[("mixed_independent_seed_size", size)] += 1
                return True
    ACTUAL_A_COUNTS["no_mixed_independent_coefficient_seed"] += 1
    return False


def fixed_seed_extension_exists(ext8, space8, fixed5, pair_block, pair_state, rank_cache):
    data = source_data(ext8, space8, pair_block, pair_state, rank_cache)
    if data is None:
        return False
    fixed_blocks = tuple(block for block, _state in fixed5)
    if len(fixed_blocks) != 5 or len(set(fixed_blocks)) != 5 or pair_block in fixed_blocks:
        return False
    for block, state in fixed5:
        if data["singleton_state"].get(block) != state:
            return False
    if mixed_extra_rank(data, fixed_blocks) != 6:
        ACTUAL_A_COUNTS["fixed_six_not_independent_at_source"] += 1
        return False

    coeff_base = data["empty_space"]
    for block in fixed_blocks:
        coeff_base = R.union_key(coeff_base, data["singleton_constraint"][block])
    ACTUAL_A_COUNTS[("fixed_seed_coefficient_rank", len(coeff_base))] += 1

    fixed_set = set(fixed_blocks)
    extras = tuple(block for block in data["singleton_vector"] if block not in fixed_set)
    for x, y in combinations(extras, 2):
        chosen = fixed_blocks + (x, y)
        if mixed_extra_rank(data, chosen) != 8:
            continue
        coeff = R.union_key(
            R.union_key(coeff_base, data["singleton_constraint"][x]),
            data["singleton_constraint"][y],
        )
        if coeff == space8:
            ACTUAL_A_COUNTS["fixed_six_two_extra_source_extensions"] += 1
            return True
    ACTUAL_A_COUNTS["no_fixed_six_two_extra_source_extension"] += 1
    return False


def fixed_global_basis_exists_with_source_prefilter(
    ext8, space8, ext7, space7, state7, ext6_seed, space6_seed,
    fixed5, pair_block, pair_state, rank_cache,
):
    ACTUAL_A_COUNTS["global_source_candidates"] += 1
    if not mixed_seed_exists(ext8, space8, pair_block, pair_state, rank_cache):
        return False
    ACTUAL_A_COUNTS["mixed_seed_survivors"] += 1
    if not fixed_seed_extension_exists(
        ext8, space8, fixed5, pair_block, pair_state, rank_cache
    ):
        return False
    ACTUAL_A_COUNTS["fixed_seed_extension_survivors"] += 1
    return ORIG_FIXED_GLOBAL_BASIS_EXISTS(
        ext8, space8, ext7, space7, state7, ext6_seed, space6_seed,
        fixed5, pair_block, pair_state, rank_cache,
    )


def fixed_extra_rank_with_actual_state(ext, space, state_data, block_states):
    if len(ext) == 8 and len(block_states) == 8:
        singleton_states = [(b, s) for b, s in block_states if s in (1, 2, 4)]
        pair_states = [(b, s) for b, s in block_states if s in (3, 5, 6)]
        if len(singleton_states) != 7 or len(pair_states) != 1:
            return -1

        touched = S.touched_blocks(ext)
        virtual_states = G.virtual_canonical(ext, touched, space)
        position = {block: i for i, block in enumerate(touched)}
        actual_states = list(virtual_states)
        for block, state in block_states:
            if block not in position:
                return -1
            pos = position[block]
            if virtual_states[pos] != 7:
                return -1
            if state in (1, 2, 4):
                options = A0.singleton_options(ext, block, space)
                if len(options) != 1 or options[0] != state:
                    return -1
            elif state in (3, 5, 6):
                if R.local_constraint_key(ext, block, state):
                    return -1
            else:
                return -1
            actual_states[pos] = state

        if actual_space(ext, touched, tuple(actual_states)) != space:
            ACTUAL_A_COUNTS["chosen_eight_wrong_coefficient_space"] += 1
            return -1
        ACTUAL_A_COUNTS["chosen_eight_realizes_coefficient_space"] += 1

        rank = ORIG_FIXED_EXTRA_RANK(ext, space, state_data, block_states)
        if rank != 8:
            return rank

        incomplete_cost = sum(
            R.STATES[state][1] for state in actual_states if state != 7
        )
        if incomplete_cost != 9:
            ACTUAL_A_COUNTS["chosen_eight_wrong_incomplete_cost"] += 1
            return -1

        actual_rows = A.generic_relation_rows(ext, touched, tuple(actual_states), space)
        actual_relation_rank = A.rank_q(actual_rows)
        nrows = len(ext) + sum(R.STATES[state][1] for state in actual_states)
        defect = nrows - 3 * actual_relation_rank
        if defect != -1:
            ACTUAL_A_COUNTS["chosen_eight_wrong_exact_defect"] += 1
            return -1
        ACTUAL_A_COUNTS["chosen_eight_exact_defect_minus1"] += 1

        if len(ACTUAL_A_EXAMPLES) < 20:
            ACTUAL_A_EXAMPLES.append(
                (tuple(ext), space, tuple(block_states), tuple(actual_states), actual_relation_rank)
            )
        return rank
    return ORIG_FIXED_EXTRA_RANK(ext, space, state_data, block_states)


A.fixed_global_basis_exists = fixed_global_basis_exists_with_source_prefilter
A.fixed_extra_rank = fixed_extra_rank_with_actual_state

if __name__ == "__main__":
    try:
        A.A0.main()
    finally:
        print("profile_a_common_basis_counts", A.C0.COMMON_BASIS_COUNTS)
        print("profile_a_common_basis_examples", A.C0.COMMON_BASIS_EXAMPLES)
        print("profile_a_global_counts", A.GLOBAL_A_COUNTS)
        print("profile_a_global_examples", A.GLOBAL_A_EXAMPLES)
        print("profile_a_actual_realization_counts", ACTUAL_A_COUNTS)
        print("profile_a_actual_realization_examples", ACTUAL_A_EXAMPLES)
