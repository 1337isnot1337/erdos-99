#!/usr/bin/env python3
"""Exact t=5, k=3, p=0 rank-density barrier for Target C.

For five no-root four-cycles, after the k=2 and k=5 audits, the remaining
possible violations of 3*delta(A)<=|A| lie in k=3,p<=3 or k=4,p<=6.
This verifier closes the p=0 subcase of k=3.

For k=3 the global coefficient-constraint space has rank two, hence a
three-dimensional coefficient nullspace. With p=0 every touched root-0 block
is empty or complete. For a fixed rank-two space P, the canonical least-row
state empties exactly the blocks whose empty constraint lies in P. Every other
realization of the same P is obtained by completing compatible empty blocks,
which adds three rows and at most one relative T direction per completion.
Thus the defect cannot decrease away from the canonical state.

Across the exact 20,451 S7 orbits of five no-root subsets, all obtainable
rank-two spaces give 246,860 canonical states. The 12,694 states with c>=14
are safe from dim(T)=15. Among the rest, 234,080 have complete-block rank
deficiency at least two and are safe before the external relations are even
formed. Only 86 deficiency-one states remain; exact relation ranks give defect
8 in every one of them.

All finite-field ranks use P=2^127-1 with Lucas-Lehmer and a Hadamard bound.
The maximum squared norm of any relation row used in the exact residual scan
is 36, and P^2 > 36^15, so the ranks agree with ranks over Q.
"""
from argparse import ArgumentParser
from collections import Counter
from pathlib import Path
import contextlib
import importlib.util
import io

HERE = Path(__file__).resolve().parent
K5 = HERE / "verify_target_c_support7_global_segment_relative_five_noroot_k5_2026_09_20.py"
spec = importlib.util.spec_from_file_location("relative_five_noroot_k5_for_k3p0", K5)
K = importlib.util.module_from_spec(spec)
with contextlib.redirect_stdout(io.StringIO()):
    spec.loader.exec_module(K)
R = K.R


COMPLETE_T = []
for ids in R.BLOCKS:
    COMPLETE_T.append(tuple(
        R.MCOORD[ids[0]][70 + j]
        - R.MCOORD[ids[1]][70 + j]
        - R.MCOORD[ids[2]][70 + j]
        for j in range(15)
    ))


def candidate_rank2_constraint_spaces(ext, touched):
    """All rank-two spans generated by local empty-state constraints."""
    spaces = {()}
    for b in touched:
        local = R.local_constraint_key(ext, b, 0)
        new = set(spaces)
        for space in spaces:
            joined = R.union_key(space, local)
            if len(joined) <= 2:
                new.add(joined)
        spaces = new
    return tuple(space for space in spaces if len(space) == 2)


def canonical_minimal_state(ext, touched, space):
    states = []
    generated = ()
    for b in touched:
        empty_key = R.local_constraint_key(ext, b, 0)
        if R.is_subspace(empty_key, space):
            states.append(0)
            generated = R.union_key(generated, empty_key)
        else:
            states.append(7)
    if generated != space:
        return None
    return tuple(states)


def relation_rows(ext, touched, states, space):
    rows = []
    for b, state in zip(touched, states):
        if state == 7:
            rows.append(COMPLETE_T[b])

    alphas = R.nullspace_int(space, 5)
    assert len(alphas) == 3
    for alpha in alphas:
        tv = [
            sum(alpha[i] * R.MCOORD[e][70 + j] for i, e in enumerate(ext))
            for j in range(15)
        ]
        for b, state in zip(touched, states):
            vx = sum(alpha[i] * R.QCOMP[e][b][0] for i, e in enumerate(ext))
            vy = sum(alpha[i] * R.QCOMP[e][b][1] for i, e in enumerate(ext))
            beta = R.solve_local_coeffs_int(R.STATES[state][0], (-vx, -vy))
            ids = R.BLOCKS[b]
            for local_index, q in enumerate(beta):
                if q:
                    for j in range(15):
                        tv[j] += q * R.MCOORD[ids[local_index]][70 + j]
        rows.append(tuple(tv))
    return rows


def scan(keys, orbits, start, stop):
    key_to_global = {K.cycle_key(R.DESC[e]): e for e in R.NO_ROOT}
    canonical_states = 0
    dimension_cap_states = 0
    dependency_safe_states = 0
    exact_states = 0
    deficiency_census = Counter()
    complete_count_census = Counter()
    complete_rank_census = Counter()
    exact_defect_census = Counter()
    exact_rank_census = Counter()
    complete_rank_cache = {}
    max_relation_norm2 = 0
    first_negative = None

    for orbit_index in range(start, stop):
        local_five = orbits[orbit_index]
        ext = tuple(key_to_global[keys[i]] for i in local_five)
        touched = tuple(sorted(
            b for b in range(35)
            if any(R.QCOMP[e][b] != (0, 0) for e in ext)
        ))

        for space in candidate_rank2_constraint_spaces(ext, touched):
            states = canonical_minimal_state(ext, touched, space)
            assert states is not None
            canonical_states += 1
            complete_set = tuple(
                b for b, state in zip(touched, states) if state == 7
            )
            c = len(complete_set)
            complete_count_census[c] += 1

            if c >= 14:
                dimension_cap_states += 1
                continue

            rank = complete_rank_cache.get(complete_set)
            if rank is None:
                rank = R.rank_mod([COMPLETE_T[b] for b in complete_set])
                complete_rank_cache[complete_set] = rank
            complete_rank_census[(c, rank)] += 1
            deficiency = c - rank
            deficiency_census[deficiency] += 1

            if deficiency >= 2:
                dependency_safe_states += 1
                continue

            rows = relation_rows(ext, touched, states, space)
            exact_states += 1
            for row in rows:
                max_relation_norm2 = max(
                    max_relation_norm2,
                    sum(x * x for x in row),
                )
            delta = R.rank_mod(rows)
            defect = 5 + 3 * c - 3 * delta
            exact_defect_census[defect] += 1
            exact_rank_census[(c, rank, delta)] += 1
            if defect < 0:
                first_negative = (
                    orbit_index,
                    defect,
                    delta,
                    c,
                    rank,
                    ext,
                    touched,
                    space,
                    states,
                )
                break
        if first_negative is not None:
            break

    return {
        "canonical_states": canonical_states,
        "dimension_cap_states": dimension_cap_states,
        "dependency_safe_states": dependency_safe_states,
        "exact_states": exact_states,
        "deficiency_census": deficiency_census,
        "complete_count_census": complete_count_census,
        "complete_rank_census": complete_rank_census,
        "exact_defect_census": exact_defect_census,
        "exact_rank_census": exact_rank_census,
        "complete_rank_cache_size": len(complete_rank_cache),
        "max_relation_norm2": max_relation_norm2,
        "first_negative": first_negative,
    }


def main():
    parser = ArgumentParser()
    parser.add_argument("--orbit-start", type=int, default=0)
    parser.add_argument("--orbit-end", type=int)
    args = parser.parse_args()

    assert R.lucas_lehmer_127()
    keys, orbits, orbit_sizes, augmentation_candidates = K.five_no_root_orbits()
    end = len(orbits) if args.orbit_end is None else args.orbit_end
    assert 0 <= args.orbit_start <= end <= len(orbits)

    result = scan(keys, orbits, args.orbit_start, end)
    assert result["first_negative"] is None, result["first_negative"]

    max_complete_norm2 = max(sum(x * x for x in row) for row in COMPLETE_T)
    bound_norm2 = max(max_complete_norm2, result["max_relation_norm2"])
    assert R.P * R.P > max(1, bound_norm2) ** 15

    if args.orbit_start == 0 and end == len(orbits):
        assert len(orbits) == 20451
        assert sum(orbit_sizes) == 96560646
        assert augmentation_candidates == 20475
        assert result["canonical_states"] == 246860
        assert result["dimension_cap_states"] == 12694
        assert result["dependency_safe_states"] == 234080
        assert result["exact_states"] == 86
        assert dict(sorted(result["deficiency_census"].items())) == {
            1: 86,
            2: 13349,
            3: 219112,
            4: 1619,
        }
        assert dict(sorted(result["exact_defect_census"].items())) == {8: 86}
        assert dict(sorted(result["exact_rank_census"].items())) == {
            (4, 3, 3): 70,
            (6, 5, 5): 4,
            (7, 6, 6): 12,
        }
        assert result["max_relation_norm2"] == 36

    print("PASS: five-no-root k=3,p=0 rank-density branch")
    print("five_no_root_subsets", 96560646)
    print("S7_orbits", len(orbits))
    print("orbit_range", args.orbit_start, end)
    print("canonical_rank2_constraint_states", result["canonical_states"])
    print("dimension_cap_states", result["dimension_cap_states"])
    print("dependency_safe_states", result["dependency_safe_states"])
    print("exact_states", result["exact_states"])
    print("complete_rank_deficiency_census", dict(sorted(result["deficiency_census"].items())))
    print("exact_defect_census", dict(sorted(result["exact_defect_census"].items())))
    print("exact_rank_census", dict(sorted(result["exact_rank_census"].items())))
    print("max_complete_row_norm_squared", max_complete_norm2)
    print("max_relation_row_norm_squared", result["max_relation_norm2"])
    print("hadamard_exact_rank_bound", R.P * R.P > max(1, bound_norm2) ** 15)
    print("complete_rank_cache_size", result["complete_rank_cache_size"])


if __name__ == "__main__":
    main()
