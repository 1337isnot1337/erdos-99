#!/usr/bin/env python3
"""Exact six-ray regression for the three-dominant full-flower normal form."""
from itertools import product

# Triangular lattice coordinate a=(1,0), b=(1/2,sqrt(3)/2).
rays=[(1,0),(0,1),(-1,1),(-1,0),(0,-1),(1,-1)]

def add(vs):
    return sum(x for x,_ in vs),sum(y for _,y in vs)
def norm2(v):
    m,n=v
    return m*m+m*n+n*n

def opposite(i,j):
    return (i-j)%6==3

spectrum=set()
classes={}
for idx in product(range(6),repeat=3):
    s=add([rays[i] for i in idx])
    q=norm2(s)
    spectrum.add(q)
    has_opp=any(opposite(idx[i],idx[j]) for i in range(3) for j in range(i+1,3))
    classes.setdefault((q,has_opp),0)
    classes[(q,has_opp)]+=1

assert spectrum=={0,1,3,4,7,9}
# Every norm-one triple has an opposite pair.
assert all(has_opp for (q,has_opp),count in classes.items() if q==1 and count)
# A no-opposite triple which can close with two unit vectors has only q=0,3,4.
assert all(q in (0,3,4) for (q,opp),count in classes.items() if not opp and q<=4 and count)

# q=0 triples are exactly one of the two alternating ray triples as multisets.
alternating={tuple(sorted((0,2,4))),tuple(sorted((1,3,5)))}
for idx in product(range(6),repeat=3):
    if norm2(add([rays[i] for i in idx]))==0:
        assert tuple(sorted(idx)) in alternating

# Norm-four lattice vectors generated by three rays are twice a unit ray.
for idx in product(range(6),repeat=3):
    s=add([rays[i] for i in idx])
    if norm2(s)==4:
        assert s[0]%2==0 and s[1]%2==0
        half=(s[0]//2,s[1]//2)
        assert half in rays

# Norm-three lattice vectors point between adjacent unit rays. Enumerate the unit
# pairs whose sum is -s and check they are adjacent six-ray directions.
for idx in product(range(6),repeat=3):
    s=add([rays[i] for i in idx])
    if norm2(s)!=3:
        continue
    target=(-s[0],-s[1])
    pairs=[]
    for i in range(6):
        for j in range(i,6):
            if add([rays[i],rays[j]])==target:
                pairs.append((i,j))
    assert pairs
    for i,j in pairs:
        assert (i-j)%6 in (1,5)

print('PASS three-dominant full-flower through-pair regression')
print('three-ray norm^2 spectrum =',sorted(spectrum))
print('class counts =',sorted(classes.items()))
