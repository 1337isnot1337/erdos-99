#!/usr/bin/env python3
"""Coverage-correct containment theorem for the five-no-root k=3 branch.

The earlier verifier scanned only rank-two coefficient spaces P generated by
empty-block constraints.  That is not exhaustive once singleton incomplete
blocks are allowed.  This verifier enumerates every realizable rank-two P.
At one root-0 quotient block, only the empty state and singleton states impose
nonzero coefficient constraints; pair and complete states span the local
quotient and impose none.  Since rank(P)=2, at most two singleton constraints
are needed in a basis.  A block-by-block exact row-space DP therefore covers
all possible P while respecting one local state per block.

For each P, define the virtual canonical state by leaving block b empty iff its
empty-state constraint lies in P and completing it otherwise.  Let C be its
complete-block set and d=|C|-rank H(C), with H(C) the span of the corresponding
complete-block T-relations.  The exhaustive scan proves d>=1 and proves that
all three external null(P) T-relations lie in H(C) for every P.

For an actual realization, changing q canonical-complete blocks to incomplete
states can alter an external T-lift only by complete-block relations already in
H(C).  Canonical-empty blocks have zero local demand for alpha in null(P).
Completing an additional canonical-empty block adds three rows and at most one
T direction.  Hence

    D(A)=|A|-3*delta(A) >= 5 + p + 3d - 3q,

and q<=p because a canonical-complete block cannot become empty.  Thus p<=3
gives D>=2.  This repairs the documented candidate-space coverage gap.

Across all 20,451 S7 representatives the scan finds 535,040 possible rank-two
P: 246,860 empty-generated, 215,498 requiring one singleton in a minimum
generating set, and 72,682 requiring two.  Only the empty-generated class has
d=1; all 288,180 formerly omitted planes have d>=2.  The maximum squared
relation-row norm is 48.  With MOD=2^127-1, Lucas-Lehmer and the checked bound
MOD^2>48^15 make every modular rank and containment decision exact over Q.
"""
from argparse import ArgumentParser
from collections import Counter
from fractions import Fraction
from pathlib import Path
import contextlib
import importlib.util
import io

HERE = Path(__file__).resolve().parent
RESEARCH = HERE if HERE.name == "research" else HERE / "research"
BASE = RESEARCH / "verify_target_c_support7_global_segment_relative_five_noroot_k3_p0_2026_09_20.py"
spec = importlib.util.spec_from_file_location("k3_general_p0", BASE)
P0 = importlib.util.module_from_spec(spec)
with contextlib.redirect_stdout(io.StringIO()):
    spec.loader.exec_module(P0)
R = P0.R
K = P0.K
MOD = R.P

EXPECTED = {
    (0, 1): 86, (0, 2): 13349, (0, 3): 229678, (0, 4): 3657,
    (0, 5): 84, (0, 6): 6,
    (1, 2): 2383, (1, 3): 69456, (1, 4): 136800, (1, 5): 6811,
    (1, 6): 48,
    (2, 2): 133, (2, 3): 5728, (2, 4): 32810, (2, 5): 30524,
    (2, 6): 3429, (2, 7): 58,
}

GAP_EXT = (106, 109, 112, 105, 107)
GAP_TOUCHED = (0, 1, 2, 3, 5, 6, 7, 15, 16, 17)
GAP_SPACE = (
    (Fraction(0), Fraction(0), Fraction(1), Fraction(0), Fraction(0)),
    (Fraction(0), Fraction(0), Fraction(0), Fraction(1), Fraction(1)),
)


def candidate_spaces(ext, touched):
    """All realizable rank-two P and minimum singleton generators needed."""
    best = {(): 0}
    for b in touched:
        empty = R.local_constraint_key(ext, b, 0)
        singles = {
            R.local_constraint_key(ext, b, state)
            for state in (1, 2, 4)
        } - {()}
        new = dict(best)
        for space, cost in best.items():
            joined = R.union_key(space, empty)
            if len(joined) <= 2:
                old = new.get(joined)
                if old is None or cost < old:
                    new[joined] = cost
            for key in singles:
                joined = R.union_key(space, key)
                if len(joined) <= 2:
                    old = new.get(joined)
                    if old is None or cost + 1 < old:
                        new[joined] = cost + 1
        best = new
    out = tuple((space, cost) for space, cost in best.items() if len(space) == 2)
    assert all(cost <= 2 for _, cost in out)
    return out


def virtual_canonical(ext, touched, space):
    return tuple(
        0 if R.is_subspace(R.local_constraint_key(ext, b, 0), space) else 7
        for b in touched
    )


def rref_basis_mod(rows):
    basis = {}
    for row in rows:
        v = [int(x) % MOD for x in row]
        for pivot in sorted(basis):
            if v[pivot]:
                q = v[pivot]
                br = basis[pivot]
                v = [(x - q * y) % MOD for x, y in zip(v, br)]
        pivot = next((j for j, x in enumerate(v) if x), None)
        if pivot is None:
            continue
        inv = pow(v[pivot], -1, MOD)
        v = [x * inv % MOD for x in v]
        for old in list(basis):
            if basis[old][pivot]:
                q = basis[old][pivot]
                basis[old] = [(x - q * y) % MOD for x, y in zip(basis[old], v)]
        basis[pivot] = v
    return tuple((pivot, tuple(basis[pivot])) for pivot in sorted(basis))


def contained_mod(row, basis):
    v = [int(x) % MOD for x in row]
    for pivot, br in basis:
        if v[pivot]:
            q = v[pivot]
            v = [(x - q * y) % MOD for x, y in zip(v, br)]
    return not any(v)


def check_gap_witness():
    candidates = dict(candidate_spaces(GAP_EXT, GAP_TOUCHED))
    assert candidates[GAP_SPACE] == 1
    assert GAP_SPACE not in set(
        P0.candidate_rank2_constraint_spaces(GAP_EXT, GAP_TOUCHED)
    )
    states = virtual_canonical(GAP_EXT, GAP_TOUCHED, GAP_SPACE)
    complete = tuple(b for b, state in zip(GAP_TOUCHED, states) if state == 7)
    basis = rref_basis_mod([P0.COMPLETE_T[b] for b in complete])
    assert len(complete) - len(basis) == 2
    rows = P0.relation_rows(GAP_EXT, GAP_TOUCHED, states, GAP_SPACE)
    assert all(contained_mod(row, basis) for row in rows[len(complete):])


def scan(keys, orbits, start, stop):
    key_to_global = {K.cycle_key(R.DESC[e]): e for e in R.NO_ROOT}
    cache = {}
    census = Counter()
    max_norm2 = 0
    first_failure = None

    for orbit_index in range(start, stop):
        ext = tuple(key_to_global[keys[i]] for i in orbits[orbit_index])
        touched = tuple(sorted(
            b for b in range(35)
            if any(R.QCOMP[e][b] != (0, 0) for e in ext)
        ))
        for space, min_singletons in candidate_spaces(ext, touched):
            states = virtual_canonical(ext, touched, space)
            complete = tuple(b for b, state in zip(touched, states) if state == 7)
            basis = cache.get(complete)
            if basis is None:
                basis = rref_basis_mod([P0.COMPLETE_T[b] for b in complete])
                cache[complete] = basis
            deficiency = len(complete) - len(basis)
            census[(min_singletons, deficiency)] += 1
            if deficiency < 1:
                first_failure = ("deficiency", orbit_index, ext, space, complete)
                break

            rows = P0.relation_rows(ext, touched, states, space)
            external = rows[len(complete):]
            assert len(external) == 3
            for row in external:
                max_norm2 = max(max_norm2, sum(x * x for x in row))
                if not contained_mod(row, basis):
                    first_failure = (
                        "containment", orbit_index, ext, space, complete,
                        deficiency, row,
                    )
                    break
            if first_failure is not None:
                break
        if first_failure is not None:
            break

    return census, max_norm2, len(cache), first_failure


def main():
    parser = ArgumentParser()
    parser.add_argument("--orbit-start", type=int, default=0)
    parser.add_argument("--orbit-end", type=int)
    args = parser.parse_args()

    assert R.lucas_lehmer_127()
    check_gap_witness()
    keys, orbits, orbit_sizes, augmentation_candidates = K.five_no_root_orbits()
    end = len(orbits) if args.orbit_end is None else args.orbit_end
    assert 0 <= args.orbit_start <= end <= len(orbits)

    census, max_norm2, cache_size, failure = scan(
        keys, orbits, args.orbit_start, end
    )
    assert failure is None, failure

    max_complete_norm2 = max(sum(x * x for x in row) for row in P0.COMPLETE_T)
    bound = max(max_complete_norm2, max_norm2)
    assert MOD * MOD > max(1, bound) ** 15

    if args.orbit_start == 0 and end == len(orbits):
        assert len(orbits) == 20451
        assert sum(orbit_sizes) == 96560646
        assert augmentation_candidates == 20475
        assert sum(census.values()) == 535040
        assert dict(sorted(census.items())) == EXPECTED
        assert sum(v for (cost, _), v in census.items() if cost == 0) == 246860
        assert sum(v for (cost, _), v in census.items() if cost > 0) == 288180
        assert not any(cost > 0 and deficiency == 1 for cost, deficiency in census)
        assert max_norm2 == 48
        assert max_complete_norm2 == 12

    print("PASS: coverage-correct five-no-root k=3 containment")
    print("five_no_root_subsets", 96560646)
    print("S7_orbits", len(orbits))
    print("orbit_range", args.orbit_start, end)
    print("virtual_canonical_states", sum(census.values()))
    print("minimum_singletons_deficiency_census", dict(sorted(census.items())))
    print("max_complete_row_norm_squared", max_complete_norm2)
    print("max_external_row_norm_squared", max_norm2)
    print("hadamard_exact_rank_bound", MOD * MOD > max(1, bound) ** 15)
    print("basis_cache_size", cache_size)


if __name__ == "__main__":
    main()
