#!/usr/bin/env python3
"""Close the seven-no-root D=-2,k=4,d=0,p=3 Target-C branch.

Inputs already proved elsewhere in the repository:

* the coefficient space P <= Q^7 has rank 3 and generalized weights
  (d1,d2,d3) >= (3,4,6);
* the incomplete-root cost p=3 consists of exactly three singleton blocks;
* each singleton block is touched by at least three of the seven no-root
  cycles;
* for each singleton b, its singleton constraint L_b lies in P while its
  empty constraint E_b is not contained in P.

This verifier checks the finite geometry used after the analytic reduction
that all three singleton blocks have rank-one local empty spaces.  Such a
singleton is aligned: all no-root cycles touching it have the same local
projective direction, so it is touched by exactly 3 or 4 of the four cycles
available in that direction.

Up to S_7, only three triples of root blocks can host three aligned singleton
supports of size at least 3 inside seven no-root cycles.  They yield exactly
789 seven-cycle configurations.  For each configuration the script exhausts
every rank-three coefficient space generated by empty constraints on the
remaining touched blocks.  There are 41,388 configuration/space candidates.
Exact rational puncturing rejects every one by the already-proved generalized
weight conditions.  Thus no state reaches the complete-block or T-space
reranking stage.

All linear algebra in the final finite search is over fractions.Fraction.
There is no finite-field rank heuristic in this certificate.
"""
from collections import Counter
from fractions import Fraction
from functools import lru_cache
from itertools import combinations, permutations
from pathlib import Path
import contextlib
import importlib.util
import io

HERE = Path(__file__).resolve().parent
BASE = HERE / "verify_target_c_support7_global_segment_relative_four_noroot_k2_2026_09_20.py"
spec = importlib.util.spec_from_file_location("seven_k4_d0p3_base", BASE)
R = importlib.util.module_from_spec(spec)
with contextlib.redirect_stdout(io.StringIO()):
    spec.loader.exec_module(R)

DIRS = ((1, 0), (0, 1), (1, -1))


def projective_direction(v):
    """Normalize the six nonzero local vectors to the three projective lines."""
    x, y = v
    assert (x, y) != (0, 0)
    if x == 0:
        return (0, 1)
    if y == 0:
        return (1, 0)
    assert x == -y
    return (1, -1)


def touched_cycles(block):
    return tuple(e for e in R.NO_ROOT if R.QCOMP[e][block] != (0, 0))


def geometry_checks():
    """Certify the local 4+4+4 direction geometry and pair intersections."""
    for b in range(35):
        count = Counter(
            projective_direction(R.QCOMP[e][b]) for e in touched_cycles(b)
        )
        assert count == Counter({d: 4 for d in DIRS})

    # Two distinct root triples are co-touched iff they share two vertices.
    # In that case the three common no-root cycles are the three 4-cycle
    # orientations of their union, and give all three directions at each face.
    for a, b in combinations(range(35), 2):
        common = tuple(set(touched_cycles(a)) & set(touched_cycles(b)))
        inter = len(set(R.BLOCK_LABELS[a]) & set(R.BLOCK_LABELS[b]))
        if inter == 2:
            assert len(common) == 3
            assert {
                projective_direction(R.QCOMP[e][a]) for e in common
            } == set(DIRS)
            assert {
                projective_direction(R.QCOMP[e][b]) for e in common
            } == set(DIRS)
        else:
            assert not common

    # Local arithmetic used in the analytic rank-two exclusion.  If a
    # rank-two singleton has t touches, the generalized-weight/coset bounds
    # force each direction multiplicity m_i <= t-3.  Therefore t>=5, and at
    # t=5 the only profile is (2,2,1) up to permutation.
    feasible = []
    for t in range(3, 8):
        profiles = []
        for m0 in range(5):
            for m1 in range(5):
                for m2 in range(5):
                    if m0 + m1 + m2 != t:
                        continue
                    if max(m0, m1, m2) <= t - 3:
                        profiles.append(tuple(sorted((m0, m1, m2))))
        feasible.append((t, tuple(sorted(set(profiles)))))
    assert feasible[0][1] == ()
    assert feasible[1][1] == ()
    assert feasible[2][1] == ((1, 2, 2),)


def block_triple_orbit_representatives():
    """Exact S_7 orbits of triples of the 35 root blocks."""
    vertices = tuple(range(1, 8))
    labels = tuple(R.BLOCK_LABELS)
    index = {b: i for i, b in enumerate(labels)}
    maps = []
    for perm in permutations(vertices):
        p = dict(zip(vertices, perm))
        maps.append(tuple(
            index[tuple(sorted(p[x] for x in block))]
            for block in labels
        ))

    seen = set()
    reps = []
    for triple in combinations(range(35), 3):
        if triple in seen:
            continue
        orbit = {
            tuple(sorted((m[triple[0]], m[triple[1]], m[triple[2]])))
            for m in maps
        }
        seen.update(orbit)
        reps.append(min(orbit))
    assert len(reps) == 10
    assert len(seen) == 6545
    return tuple(sorted(reps))


def pair_intersection_signature(rep):
    return tuple(sorted((
        len(set(R.BLOCK_LABELS[a]) & set(R.BLOCK_LABELS[b]))
        for a, b in combinations(rep, 2)
    ), reverse=True))


def surviving_block_representatives():
    reps = block_triple_orbit_representatives()
    # Three aligned supports of size >=3 contribute >=9 incidences among only
    # seven cycles.  Since two aligned singleton supports intersect in at most
    # one cycle, at least two block pairs must be co-touchable, i.e. have
    # two-vertex intersection.
    survivors = tuple(
        rep for rep in reps
        if pair_intersection_signature(rep).count(2) >= 2
    )
    labels = tuple(tuple(R.BLOCK_LABELS[b] for b in rep) for rep in survivors)
    assert labels == (
        ((1, 2, 3), (1, 2, 4), (1, 2, 5)),
        ((1, 2, 3), (1, 2, 4), (1, 3, 4)),
        ((1, 2, 3), (1, 2, 4), (1, 3, 5)),
    )
    return survivors


def aligned_options(block):
    """All actual touch sets for a rank-one sharp singleton block."""
    by_direction = {
        d: tuple(
            e for e in R.NO_ROOT
            if R.QCOMP[e][block] != (0, 0)
            and projective_direction(R.QCOMP[e][block]) == d
        )
        for d in DIRS
    }
    assert all(len(es) == 4 for es in by_direction.values())
    out = []
    for d, es in by_direction.items():
        for size in (3, 4):
            out.extend((frozenset(S), d) for S in combinations(es, size))
    assert len(out) == 15
    return tuple(out)


ALIGNED = {b: aligned_options(b) for b in range(35)}


def generate_configurations(rep):
    """All seven-cycle sets inducing aligned supports on one block triple."""
    touched_any = {
        e for e in R.NO_ROOT
        if any(R.QCOMP[e][b] != (0, 0) for b in rep)
    }
    seen = set()
    out = []
    for a in ALIGNED[rep[0]]:
        for b in ALIGNED[rep[1]]:
            union_ab = a[0] | b[0]
            if len(union_ab) > 7:
                continue
            for c in ALIGNED[rep[2]]:
                base = union_ab | c[0]
                if len(base) > 7:
                    continue
                need = 7 - len(base)
                available = tuple(
                    e for e in R.NO_ROOT
                    if e not in base and e not in touched_any
                )
                for fill in combinations(available, need):
                    ext = tuple(sorted(set(base) | set(fill)))
                    directions = (a[1], b[1], c[1])
                    key = (ext, directions)
                    if key in seen:
                        continue
                    # The chosen options must be the full induced touch sets;
                    # fillers are not allowed to silently change a singleton.
                    options = (a, b, c)
                    if any(
                        frozenset(
                            e for e in ext if R.QCOMP[e][block] != (0, 0)
                        ) != option[0]
                        for block, option in zip(rep, options)
                    ):
                        continue
                    seen.add(key)
                    out.append(key)
    return tuple(out)


def rowspace_key(rows):
    """Canonical exact rational RREF row-space key."""
    basis = {}
    for row in rows:
        r = [Fraction(x) for x in row]
        for pivot in sorted(basis):
            if r[pivot]:
                q = r[pivot]
                br = basis[pivot]
                r = [x - q * y for x, y in zip(r, br)]
        pivot = next((i for i, x in enumerate(r) if x), None)
        if pivot is None:
            continue
        q = r[pivot]
        r = [x / q for x in r]
        for old in list(basis):
            if basis[old][pivot]:
                q0 = basis[old][pivot]
                basis[old] = [
                    x - q0 * y for x, y in zip(basis[old], r)
                ]
        basis[pivot] = r
    return tuple(tuple(basis[p]) for p in sorted(basis))


@lru_cache(maxsize=None)
def union_space(a, b):
    return rowspace_key(a + b)


def local_empty_space(ext, block):
    vals = tuple(R.QCOMP[e][block] for e in ext)
    return rowspace_key((
        tuple(v[0] for v in vals),
        tuple(v[1] for v in vals),
    ))


def project_space(space, drops):
    drops = frozenset(drops)
    return rowspace_key(tuple(
        tuple(x for j, x in enumerate(row) if j not in drops)
        for row in space
    ))


def satisfies_generalized_weights(space):
    """Exact (d1,d2,d3)>=(3,4,6) test for a rank-three length-7 code."""
    assert len(space) == 3
    # d1>=3: no nonzero vector is supported on a deleted pair.
    if any(len(project_space(space, J)) != 3 for J in combinations(range(7), 2)):
        return False
    # d2>=4: no two-dimensional subcode is supported on a deleted triple.
    if any(len(project_space(space, J)) < 2 for J in combinations(range(7), 3)):
        return False
    # d3>=6: the whole three-space is not supported on five coordinates.
    if any(len(project_space(space, J)) < 1 for J in combinations(range(7), 5)):
        return False
    return True


def candidate_spaces(ext, singleton_blocks):
    """Every rank-three P generated by empty non-singleton touched blocks."""
    touched = tuple(
        b for b in range(35)
        if any(R.QCOMP[e][b] != (0, 0) for e in ext)
    )
    spaces = {()}
    for b in touched:
        if b in singleton_blocks:
            continue
        empty = local_empty_space(ext, b)
        new = set(spaces)
        for space in spaces:
            joined = union_space(space, empty)
            if len(joined) <= 3:
                new.add(joined)
        spaces = new
    return tuple(space for space in spaces if len(space) == 3)


def main():
    geometry_checks()
    reps = surviving_block_representatives()

    configuration_counts = []
    candidate_counts = []
    survivors = []
    for rep in reps:
        configs = generate_configurations(rep)
        configuration_counts.append(len(configs))
        count = 0
        for ext, _directions in configs:
            spaces = candidate_spaces(ext, frozenset(rep))
            count += len(spaces)
            for space in spaces:
                if satisfies_generalized_weights(space):
                    survivors.append((rep, ext, space))
        candidate_counts.append(count)

    assert tuple(configuration_counts) == (654, 81, 54)
    assert sum(configuration_counts) == 789
    assert tuple(candidate_counts) == (34986, 3996, 2406)
    assert sum(candidate_counts) == 41388
    assert survivors == []

    print("PASS: seven-no-root D=-2,k=4,d=0,p=3 coefficient-space closure")
    print("block_triple_orbits", 10)
    print("surviving_block_triple_orbits", len(reps))
    print("configuration_counts", tuple(configuration_counts))
    print("seven_cycle_configurations", sum(configuration_counts))
    print("rank3_candidate_counts", tuple(candidate_counts))
    print("rank3_coefficient_candidates", sum(candidate_counts))
    print("generalized_weight_survivors", len(survivors))


if __name__ == "__main__":
    main()
