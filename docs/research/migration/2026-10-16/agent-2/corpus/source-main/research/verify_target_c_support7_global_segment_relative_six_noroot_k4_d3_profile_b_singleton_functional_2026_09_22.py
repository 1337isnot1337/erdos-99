HERE = Path(__file__).resolve().parent
BASE = HERE / "verify_target_c_support7_global_segment_relative_six_noroot_k4_d2_singleton_capacity_2026_09_21.py"
spec = importlib.util.spec_from_file_location("e99_k6_profile_b_cover_base", BASE)
A = importlib.util.module_from_spec(spec)
with contextlib.redirect_stdout(io.StringIO()):
    spec.loader.exec_module(A)

S = A.S
G = A.G
P0 = A.P0
R = A.R
K = A.K
MOD = A.MOD


def rank_mod_rows(rows):
    if not rows:
        return 0
    a = [[int(x) % MOD for x in row] for row in rows]
    nr = len(a)
    nc = len(a[0])
    rank = 0
    for col in range(nc):
        pivot = next((i for i in range(rank, nr) if a[i][col]), None)
        if pivot is None:
            continue
        a[rank], a[pivot] = a[pivot], a[rank]
        inv = pow(a[rank][col], -1, MOD)
        a[rank] = [(x * inv) % MOD for x in a[rank]]
        for i in range(nr):
            if i == rank or not a[i][col]:
                continue
            q = a[i][col]
            a[i] = [(x - q * y) % MOD for x, y in zip(a[i], a[rank])]
        rank += 1
        if rank == nr:
            break
    return rank


def singleton_options(ext, block, space):
    return tuple(
        state
        for state in (1, 2, 4)
        if R.is_subspace(R.local_constraint_key(ext, block, state), space)
    )


def replacement_functional(ext, block, state, space, complete_index, c):
    t = len(ext)
    nullity = t - len(space)
    out = [0] * (c + nullity)
    out[complete_index[block]] = 1
    alphas = R.nullspace_int(space, t)
    assert len(alphas) == nullity
    for i, alpha in enumerate(alphas):
        vx = sum(alpha[j] * R.QCOMP[e][block][0] for j, e in enumerate(ext))
        vy = sum(alpha[j] * R.QCOMP[e][block][1] for j, e in enumerate(ext))
        beta_complete = R.solve_local_coeffs_int(7, (-vx, -vy))
        beta_new = R.solve_local_coeffs_int(state, (-vx, -vy))
        diff = [beta_new[j] - beta_complete[j] for j in range(3)]
        lam = diff[0]
        assert diff == [lam, -lam, -lam]
        out[c + i] = -lam
    return tuple(out)


def compatible_singleton_span(ext, space, complete, rows):
    """Return (block capacity, extra rank, max multiplicity, norms, width)."""
    c = len(complete)
    complete_rank = R.rank_mod([P0.COMPLETE_T[b] for b in complete])
    assert R.rank_mod(rows) == complete_rank
    transposed = [
        tuple(rows[j][k] for j in range(len(rows)))
        for k in range(15)
    ]
    assert rank_mod_rows(transposed) == complete_rank

    complete_index = {block: i for i, block in enumerate(complete)}
    vectors = []
    capacity = 0
    max_multiplicity = 0
    max_norm2 = 0
    for block in complete:
        options = singleton_options(ext, block, space)
        if not options:
            continue
        capacity += 1
        max_multiplicity = max(max_multiplicity, len(options))
        for state in options:
            vec = replacement_functional(
                ext, block, state, space, complete_index, c
            )
            vectors.append(vec)
            max_norm2 = max(max_norm2, sum(x * x for x in vec))
    for row in transposed:
        max_norm2 = max(max_norm2, sum(x * x for x in row))
    extra = rank_mod_rows(transposed + vectors) - complete_rank
    return capacity, extra, max_multiplicity, max_norm2, len(rows)


def common_basis_block_sets(good6, projected_complete, projected_data):
    """Seven candidate basis blocks obeying every puncture-kernel bound.

    A genuine Profile-B six-row state has a seven-dimensional replacement
    quotient spanned by actual singleton classes.  Choose seven actual classes
    forming a basis.  Under puncture i the quotient map has target dimension
    3+d_i, hence kernel dimension 7-(3+d_i)=4-d_i.  Any basis block that stops
    being virtual-complete maps to zero, and distinct basis classes remain
    independent inside the kernel.  Therefore at most 4-d_i of the seven basis
    blocks can disappear from the canonical-complete set of puncture i.

    We ignore the functional independence and actual singleton-state choices
    here, so this remains a necessary overapproximation.
    """
    out = []
    projected_sets = tuple(set(x) for x in projected_complete)
    for blocks in combinations(good6, 7):
        if all(
            sum(block not in complete_i for block in blocks) <= 4 - d_i
            for complete_i, (d_i, _cap_i, _span_i)
            in zip(projected_sets, projected_data)
        ):
            out.append(blocks)
    return tuple(out)


def scan(start, stop, stop_on_survivor=False):
    keys, orbits, orbit_sizes, augmentation_candidates = K.five_no_root_orbits()
    assert len(orbits) == 20451
    assert sum(orbit_sizes) == 96560646
    assert augmentation_candidates == 20475
    key_to_global = {K.cycle_key(R.DESC[e]): e for e in R.NO_ROOT}

    rank_cache = {}
    counts = Counter()
    parent_capacity = Counter()
    parent_span = Counter()
    six_capacity = Counter()
    six_span = Counter()
    projected_profile = Counter()
    common_basis_census = Counter()
    max_relation_norm2 = 0
    max_functional_norm2 = 0
    max_functional_width = 0
    max_singleton_multiplicity = 0
    survivors = []

    for orbit_index in range(start, stop):
        ext5 = tuple(key_to_global[keys[i]] for i in orbits[orbit_index])
        touched5 = S.touched_blocks(ext5)

        for parent_space, _min_singletons in G.candidate_spaces(ext5, touched5):
            states5 = G.virtual_canonical(ext5, touched5, parent_space)
            complete5 = tuple(
                b for b, state in zip(touched5, states5) if state == 7
            )
            d5 = S.deficiency(complete5, rank_cache)
            if d5 not in (2, 3):
                continue
            counts[("five_parent_d", d5)] += 1
            need5 = 3 + d5
            good5 = A.compatible_singleton_blocks(ext5, parent_space, complete5)
            parent_capacity[(d5, len(good5))] += 1
            if len(good5) < need5:
                continue

            rows5 = P0.relation_rows(ext5, touched5, states5, parent_space)
            for row in rows5:
                max_relation_norm2 = max(
                    max_relation_norm2, sum(x * x for x in row)
                )
            cap5, span5, mult5, norm5, width5 = compatible_singleton_span(
                ext5, parent_space, complete5, rows5
            )
            assert cap5 == len(good5)
            max_singleton_multiplicity = max(max_singleton_multiplicity, mult5)
            max_functional_norm2 = max(max_functional_norm2, norm5)
            max_functional_width = max(max_functional_width, width5)
            parent_span[(d5, span5)] += 1
            if span5 < need5:
                continue
            assert span5 == need5
            counts[("five_full_span_d", d5)] += 1

            for extra in R.NO_ROOT:
                if extra in ext5:
                    continue
                counts["parent_extensions"] += 1
                ext6 = ext5 + (extra,)
                touched6 = S.touched_blocks(ext6)

                for space in S.candidate_six_planes(ext6, touched6, parent_space):
                    counts["candidate_P6"] += 1
                    projections = tuple(S.project_space(space, i) for i in range(6))
                    if any(len(projected) != 2 for projected in projections):
                        continue
                    counts["synchronized_P6"] += 1

                    states6 = G.virtual_canonical(ext6, touched6, space)
                    complete6 = tuple(
                        b for b, state in zip(touched6, states6) if state == 7
                    )
                    if S.deficiency(complete6, rank_cache) != 3:
                        continue
                    counts["synchronized_d3"] += 1

                    good6 = A.compatible_singleton_blocks(ext6, space, complete6)
                    six_capacity[len(good6)] += 1
                    if len(good6) < 7:
                        continue
                    counts["six_d3_capacity7"] += 1

                    projected_data = []
                    projected_complete = []
                    projections_ok = True
                    for i, projected in enumerate(projections):
                        ext_i = ext6[:i] + ext6[i + 1:]
                        touched_i, complete_i = S.canonical_complete_set(ext_i, projected)
                        d_i = S.deficiency(complete_i, rank_cache)
                        if d_i not in (2, 3):
                            projections_ok = False
                            break
                        need_i = 3 + d_i
                        good_i = A.compatible_singleton_blocks(
                            ext_i, projected, complete_i
                        )
                        if len(good_i) < need_i:
                            projections_ok = False
                            break
                        states_i = G.virtual_canonical(ext_i, touched_i, projected)
                        rows_i = P0.relation_rows(ext_i, touched_i, states_i, projected)
                        for row in rows_i:
                            max_relation_norm2 = max(
                                max_relation_norm2, sum(x * x for x in row)
                            )
                        cap_i, span_i, mult_i, norm_i, width_i = (
                            compatible_singleton_span(
                                ext_i, projected, complete_i, rows_i
                            )
                        )
                        assert cap_i == len(good_i)
                        max_singleton_multiplicity = max(
                            max_singleton_multiplicity, mult_i
                        )
                        max_functional_norm2 = max(
                            max_functional_norm2, norm_i
                        )
                        max_functional_width = max(
                            max_functional_width, width_i
                        )
                        projected_profile[(d_i, cap_i, span_i)] += 1
                        if span_i < need_i:
                            projections_ok = False
                            break
                        assert span_i == need_i
                        projected_data.append((d_i, cap_i, span_i))
                        projected_complete.append(complete_i)
                    if not projections_ok:
                        continue
                    counts["all_five_projections_full"] += 1

                    basis_block_sets = common_basis_block_sets(
                        good6, tuple(projected_complete), tuple(projected_data)
                    )
                    common_basis_census[len(basis_block_sets)] += 1
                    if not basis_block_sets:
                        continue
                    counts["common_seven_basis_block_set"] += 1

                    rows6 = S.relation_rows_six(ext6, touched6, states6, space)
                    for row in rows6:
                        max_relation_norm2 = max(
                            max_relation_norm2, sum(x * x for x in row)
                        )
                    cap6, span6, mult6, norm6, width6 = compatible_singleton_span(
                        ext6, space, complete6, rows6
                    )
                    assert cap6 == len(good6)
                    max_singleton_multiplicity = max(
                        max_singleton_multiplicity, mult6
                    )
                    max_functional_norm2 = max(max_functional_norm2, norm6)
                    max_functional_width = max(max_functional_width, width6)
                    six_span[span6] += 1
                    if span6 < 7:
                        continue
                    assert span6 == 7
                    counts["six_full_singleton_span7"] += 1

                    if len(survivors) < 20:
                        survivors.append(
                            (
                                orbit_index,
                                ext6,
                                space,
                                complete6,
                                good6,
                                tuple(projected_data),
                                basis_block_sets[:20],
                            )
                        )
                    if stop_on_survivor:
                        return {
                            "counts": counts,
                            "parent_capacity": parent_capacity,
                            "parent_span": parent_span,
                            "six_capacity": six_capacity,
                            "six_span": six_span,
                            "projected_profile": projected_profile,
                            "common_basis_census": common_basis_census,
                            "max_relation_norm2": max_relation_norm2,
                            "max_functional_norm2": max_functional_norm2,
                            "max_functional_width": max_functional_width,
                            "max_singleton_multiplicity": max_singleton_multiplicity,
                            "survivors": survivors,
                            "rank_cache_size": len(rank_cache),
                        }

    return {
        "counts": counts,
        "parent_capacity": parent_capacity,
        "parent_span": parent_span,
        "six_capacity": six_capacity,
        "six_span": six_span,
        "projected_profile": projected_profile,
        "common_basis_census": common_basis_census,
        "max_relation_norm2": max_relation_norm2,
        "max_functional_norm2": max_functional_norm2,
        "max_functional_width": max_functional_width,
        "max_singleton_multiplicity": max_singleton_multiplicity,
        "survivors": survivors,
        "rank_cache_size": len(rank_cache),
    }


def main():
    parser = ArgumentParser()
    parser.add_argument("--orbit-start", type=int, default=0)
    parser.add_argument("--orbit-end", type=int)
    parser.add_argument("--stop-on-survivor", action="store_true")
    parser.add_argument("--require-no-survivors", action="store_true")
    args = parser.parse_args()

    assert R.lucas_lehmer_127()
    _, orbits, _, _ = K.five_no_root_orbits()
    end = len(orbits) if args.orbit_end is None else args.orbit_end
    assert 0 <= args.orbit_start <= end <= len(orbits)

    result = scan(args.orbit_start, end, args.stop_on_survivor)

    assert MOD * MOD > max(1, result["max_relation_norm2"]) ** 15
    if result["max_functional_width"]:
        assert (
            MOD * MOD
            > max(1, result["max_functional_norm2"])
            ** result["max_functional_width"]
        )
    if args.require_no_survivors:
        assert not result["survivors"], result["survivors"][0]
        assert result["counts"]["six_full_singleton_span7"] == 0

    print("PASS: six-row rank-two d3 Profile B compatible-singleton audit")
    print("orbit_range", args.orbit_start, end)
    print("cover_counts", dict(result["counts"]))
    print("five_parent_capacity", dict(sorted(result["parent_capacity"].items())))
    print("five_parent_span", dict(sorted(result["parent_span"].items())))
    print("six_d3_capacity", dict(sorted(result["six_capacity"].items())))
    print("six_d3_singleton_span", dict(sorted(result["six_span"].items())))
    print("projected_profiles", dict(sorted(result["projected_profile"].items())))
    print(
        "common_seven_basis_block_set_census",
        dict(sorted(result["common_basis_census"].items())),
    )
    print("survivor_examples", result["survivors"])
    print("max_singleton_state_multiplicity", result["max_singleton_multiplicity"])
    print("complete_rank_cache_size", result["rank_cache_size"])
    print("max_relation_row_norm_squared", result["max_relation_norm2"])
    print("max_functional_row_norm_squared", result["max_functional_norm2"])
    print("max_functional_width", result["max_functional_width"])
    print("hadamard_exact_rank_bound", True)


if __name__ == "__main__":
    main()
