#!/usr/bin/env python3
"""Coverage-correct necessary-condition audit for eight-no-root k=6 Profile B.

Profile B is the remaining all-singleton eight-row configuration with virtual
canonical deficiency 3 and replacement-functional rank 9.  After a three-clean
puncture and one further deletion, every relevant six-row child has a rank-two
coefficient plane, virtual deficiency 3, and singleton-functional rank 7.  Each
one-coordinate puncture keeps coefficient rank two, has virtual deficiency 2 or
3, and has full singleton-functional rank 5 or 6 respectively.

This verifier is deliberately an overapproximation.  At each canonical state it
uses every compatible singleton state on every canonical-complete block, rather
than requiring one globally consistent choice of the nine actual singleton
blocks.  Therefore a zero-survivor full cover excludes Profile B rigorously;
a survivor is only a finite candidate for a later consistency audit.

Coverage begins with every repaired five-row rank-two parent that already
passes the necessary punctured full-span condition: d=2 with compatible
singleton span 5, or d=3 with span 6.  Every realizable synchronized six-row
rank-two plane projecting to such a parent is then generated by the established
six-row extension engine.  The candidate must have d6=3, compatible singleton
span 7, and all six five-row projections must again satisfy d in {2,3} and fill
the corresponding compatible-singleton quotient.
"""

