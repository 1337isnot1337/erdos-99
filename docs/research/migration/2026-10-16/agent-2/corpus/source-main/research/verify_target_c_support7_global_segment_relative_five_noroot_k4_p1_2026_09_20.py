#!/usr/bin/env python3
"""Exact t=5, k=4, p=1 rank-density barrier for Target C.

Fix the rank-one coefficient-constraint line P.  A p=1 state has exactly one
singleton incomplete block; every other incomplete block is empty.  For the
chosen singleton, the canonical state empties every other block whose empty
constraint lies in P and completes the rest.  Any other realization completes
some compatible empty blocks while P stays fixed, so it adds three selected
rows and at most one delta direction per completion.  Hence the canonical
state minimizes |A|-3 delta.

The candidate-line enumeration is exhaustive.  If the singleton constraint is
nonzero it must equal P.  If it is zero, P must be generated by a nonzero empty
constraint from another block.

If C is the canonical complete-block set, c=|C| and d=c-rank_T(C), then
    delta <= rank_T(C)+4,
so
    |A|-3 delta >= 3d-6.
Thus d>=2 is automatic, and c>=13 is automatic from delta<=15.  The exact scan
leaves 636 d=1 states; every one has defect 9.
"""
from collections import Counter
from pathlib import Path
import contextlib
import importlib.util
import io

HERE = Path(__file__).resolve().parent
P0_PATH = HERE / "verify_target_c_support7_global_segment_relative_five_noroot_k4_p0_2026_09_20.py"
spec = importlib.util.spec_from_file_location("relative_five_noroot_k4p0_for_p1", P0_PATH)
P0 = importlib.util.module_from_spec(spec)
with contextlib.redirect_stdout(io.StringIO()):
    spec.loader.exec_module(P0)
R = P0.R
K = P0.K
B = P0.B


def main():
    assert R.lucas_lehmer_127()
    keys, orbits, orbit_sizes, augmentation_candidates = K.five_no_root_orbits()
    assert len(orbits) == 20451
    assert sum(orbit_sizes) == 96560646
    assert augmentation_candidates == 20475
    key_to_global = {K.cycle_key(R.DESC[e]): e for e in R.NO_ROOT}

    complete_rank_cache = {}
    canonical_count = 0
    screen = Counter()
    exact_rank = Counter()
    exact_defect = Counter()
    max_norm2 = 0
    first_negative = None

    for local_five in orbits:
        ext = tuple(key_to_global[keys[i]] for i in local_five)
        touched = tuple(sorted(b for b in range(35) if any(R.QCOMP[e][b] != (0, 0) for e in ext)))
        constraints = {
            block: {
                state: R.local_constraint_key(ext, block, state)
                for state in (0, 1, 2, 4)
            }
            for block in touched
        }
        empty_lines = tuple({
            constraints[block][0]
            for block in touched
            if len(constraints[block][0]) == 1
        })
        orbit_seen = set()

        for singleton_block in touched:
            for singleton_state in (1, 2, 4):
                singleton_key = constraints[singleton_block][singleton_state]
                if len(singleton_key) > 1:
                    continue
                lines = (singleton_key,) if len(singleton_key) == 1 else empty_lines
                for line in lines:
                    states = []
                    generated = singleton_key == line
                    for block in touched:
                        if block == singleton_block:
                            states.append(singleton_state)
                            continue
                        empty_key = constraints[block][0]
                        if R.is_subspace(empty_key, line):
                            states.append(0)
                            generated = generated or empty_key == line
                        else:
                            states.append(7)
                    if not generated:
                        continue
                    states = tuple(states)
                    signature = (line, states)
                    if signature in orbit_seen:
                        continue
                    orbit_seen.add(signature)
                    canonical_count += 1

                    complete_set = tuple(b for b, state in zip(touched, states) if state == 7)
                    c = len(complete_set)
                    if c >= 13:
                        screen["dimension_cap"] += 1
                        continue
                    rank = complete_rank_cache.get(complete_set)
                    if rank is None:
                        rank = R.rank_mod([B.COMPLETE_T[b] for b in complete_set])
                        complete_rank_cache[complete_set] = rank
                    deficiency = c - rank
                    screen[deficiency] += 1
                    if deficiency >= 2:
                        continue

                    rows = P0.relation_rows_line(ext, touched, states, line)
                    for row in rows:
                        max_norm2 = max(max_norm2, sum(x * x for x in row))
                    delta = R.rank_mod(rows)
                    defect = 6 + 3 * c - 3 * delta
                    exact_rank[(c, rank, delta)] += 1
                    exact_defect[defect] += 1
                    if defect < 0:
                        first_negative = (
                            defect, delta, ext, touched, line,
                            singleton_block, singleton_state, states,
                        )
                        break
                if first_negative is not None:
                    break
            if first_negative is not None:
                break
        if first_negative is not None:
            break

    assert first_negative is None, first_negative
    assert canonical_count == 2251453
    assert dict(sorted(screen.items(), key=lambda item: repr(item[0]))) == {
        "dimension_cap": 1717765,
        1: 636,
        2: 90493,
        3: 374069,
        4: 68490,
    }
    assert dict(sorted(exact_rank.items())) == {
        (6, 5, 5): 156,
        (7, 6, 6): 428,
        (8, 7, 7): 10,
        (9, 8, 8): 42,
    }
    assert dict(exact_defect) == {9: 636}
    assert max_norm2 == 18
    assert R.P * R.P > max(12, max_norm2) ** 15

    print("PASS: five-no-root k=4,p=1 rank-density branch")
    print("canonical_states", canonical_count)
    print("screen_census", dict(sorted(screen.items(), key=lambda item: repr(item[0]))))
    print("exact_rank_census", dict(sorted(exact_rank.items())))
    print("exact_defect_census", dict(sorted(exact_defect.items())))
    print("max_relation_row_norm_squared", max_norm2)
    print("hadamard_exact_rank_bound", R.P * R.P > max(12, max_norm2) ** 15)


if __name__ == "__main__":
    main()
