#!/usr/bin/env python3
"""Exact closure of the seven-no-root D=-2,k=4,d=1,p=0 branch.

For a hypothetical counterexample in this branch the global coefficient space
P_7 has rank three. The established depth-two deletion theorem says that
projection after deleting any one or any two external coordinates preserves
that rank. Every five-row pair-deletion shadow therefore has

    D=2, k=2, d=1, p=0.

The verifier first enumerates every canonical rank-three five-row coefficient
state. It computes the complete-block deficiency for all such states,
including c=14,15 states that the older k=2 proof could discard by the ambient
T-rank cap. No canonical state has deficiency zero, and exactly 4,717 have
deficiency one.

For a deficiency-one parent the canonical complete-block relations have a
unique circuit S. They are a subset of the actual root complete-block rows.
Since the actual root deficiency is also one, S is the unique global root
relation and must occur in every pair-deletion shadow. Hence each block of S
must be touched by at least three of the seven no-root cycles.

For each of the 4,717 orbit-representative parents the verifier uses that touch
condition to enumerate possible pairs of added no-root cycles. It then
exhausts every rank-three P_7 generated by compatible empty-block constraints,
projecting to the parent P_5, while imposing the exact depth-two condition on
P_7. A full scan has 531,888 candidate added pairs and zero coefficient-space
extensions.

Coefficient-space generation/projection uses the exact rational row-space
machinery in the committed five-no-root verifier. Complete-block ranks use
q=2^127-1; Lucas-Lehmer and q^2 > 12^15 certify those modular ranks over Q.

Stages:
  five        scan one orbit shard and write a pickle
  merge-five  merge a complete set of five-row shards
  seven       scan one parent-index shard and write a JSON summary
  merge-seven merge a complete set of seven-row summaries and certify closure
"""
from argparse import ArgumentParser
from collections import Counter
from pathlib import Path
import contextlib
import importlib.util
import io
import json
import pickle
import time

HERE = Path(__file__).resolve().parent
BASE = HERE / "verify_target_c_support7_global_segment_relative_five_noroot_k2_2026_09_20.py"
spec = importlib.util.spec_from_file_location("seven_k4_d1p0_k2_base", BASE)
K2 = importlib.util.module_from_spec(spec)
with contextlib.redirect_stdout(io.StringIO()):
    spec.loader.exec_module(K2)
R = K2.R
K = K2.K


def touched_blocks(ext):
    return tuple(
        b for b in range(35)
        if any(R.QCOMP[e][b] != (0, 0) for e in ext)
    )


def project_space(space, drops):
    if isinstance(drops, int):
        drops = (drops,)
    drops = set(drops)
    return R.rowspace_key(tuple(
        tuple(x for j, x in enumerate(row) if j not in drops)
        for row in space
    ))


def min_distance_three(space, n):
    rank = len(space)
    return all(
        len(project_space(space, (i, j))) == rank
        for i in range(n)
        for j in range(i + 1, n)
    )


class CompleteRankCache:
    def __init__(self):
        self.cache = {}

    def rank(self, complete):
        complete = tuple(sorted(complete))
        value = self.cache.get(complete)
        if value is None:
            value = R.rank_mod([K2.COMPLETE_T[b] for b in complete])
            self.cache[complete] = value
        return value

    def deficiency(self, complete):
        return len(complete) - self.rank(complete)


def five_parent_candidates(ext, cache):
    touched = touched_blocks(ext)
    parents = []
    deficiency_census = Counter()
    complete_deficiency_census = Counter()

    for P in K2.candidate_rank3_constraint_spaces(ext, touched):
        states = K2.canonical_minimal_state(ext, touched, P)
        assert states is not None
        complete = tuple(
            b for b, state in zip(touched, states) if state == 7
        )
        deficiency = cache.deficiency(complete)
        deficiency_census[deficiency] += 1
        complete_deficiency_census[(len(complete), deficiency)] += 1
        if deficiency == 1:
            parents.append((P, complete, touched))

    return tuple(parents), deficiency_census, complete_deficiency_census


def scan_five(start, end):
    keys, orbits, orbit_sizes, augmentation_candidates = K.five_no_root_orbits()
    assert len(orbits) == 20451
    assert sum(orbit_sizes) == 96560646
    assert augmentation_candidates == 20475
    assert 0 <= start <= end <= len(orbits)

    key_to_global = {K.cycle_key(R.DESC[e]): e for e in R.NO_ROOT}
    cache = CompleteRankCache()
    parents = []
    deficiency_census = Counter()
    complete_deficiency_census = Counter()
    states_per_orbit = Counter()
    t0 = time.time()

    for orbit_index in range(start, end):
        local = orbits[orbit_index]
        ext = tuple(key_to_global[keys[i]] for i in local)
        cand, dc, cdc = five_parent_candidates(ext, cache)
        deficiency_census.update(dc)
        complete_deficiency_census.update(cdc)
        states_per_orbit[len(cand)] += 1
        for P, complete, touched in cand:
            parents.append(
                (orbit_index, tuple(local), ext, P, complete, touched)
            )

    assert deficiency_census.get(0, 0) == 0

    return {
        "start": start,
        "end": end,
        "parents": tuple(parents),
        "deficiency_census": deficiency_census,
        "complete_deficiency_census": complete_deficiency_census,
        "states_per_orbit": states_per_orbit,
        "rank_cache_size": len(cache.cache),
        "seconds": time.time() - t0,
    }


def circuit_support(complete, cache):
    rank = cache.rank(complete)
    assert len(complete) - rank == 1
    support = tuple(
        b for b in complete
        if cache.rank(tuple(x for x in complete if x != b)) == rank
    )
    assert len(support) in (4, 6, 8)
    return support


def touch_mask(e):
    mask = 0
    for b in range(35):
        if R.QCOMP[e][b] != (0, 0):
            mask |= 1 << b
    return mask


TOUCH_MASK = {e: touch_mask(e) for e in R.NO_ROOT}


def candidate_added_pairs(ext5, circuit):
    multiplicity = {
        b: sum(R.QCOMP[e][b] != (0, 0) for e in ext5)
        for b in circuit
    }
    assert all(m >= 1 for m in multiplicity.values())

    both_required = 0
    one_required = 0
    for b, m in multiplicity.items():
        if m == 1:
            both_required |= 1 << b
        elif m == 2:
            one_required |= 1 << b

    remaining = [
        e for e in R.NO_ROOT
        if e not in ext5
        and TOUCH_MASK[e] & both_required == both_required
    ]
    out = []
    for i, e in enumerate(remaining):
        emask = TOUCH_MASK[e]
        for f in remaining[i + 1:]:
            if (emask | TOUCH_MASK[f]) & one_required == one_required:
                out.append((e, f))
    return tuple(out)


def coefficient_extensions(ext7, parent_P):
    """All rank-three, depth-two-synchronized P7 extending parent_P."""
    touched = touched_blocks(ext7)
    eligible = []
    good_cache = {(): True}

    def good(space):
        value = good_cache.get(space)
        if value is None:
            value = min_distance_three(space, 7)
            good_cache[space] = value
        return value

    for b in touched:
        empty = R.local_constraint_key(ext7, b, 0)
        if (
            R.is_subspace(project_space(empty, (5, 6)), parent_P)
            and good(empty)
        ):
            eligible.append(empty)

    spaces = {()}
    for empty in eligible:
        new = set(spaces)
        for space in spaces:
            joined = R.union_key(space, empty)
            if len(joined) <= 3 and good(joined):
                new.add(joined)
        spaces = new

    out = tuple(
        P for P in spaces
        if len(P) == 3
        and project_space(P, (5, 6)) == parent_P
    )
    return out, len(spaces), len(eligible)


def scan_seven(merged, start, end):
    parents = tuple(merged["parents"])
    assert len(parents) == 4717
    assert 0 <= start <= end <= len(parents)

    cache = CompleteRankCache()
    circuit_census = Counter()
    raw_pairs = 0
    extension_spaces = 0
    max_intermediate_spaces = 0
    max_eligible_blocks = 0
    first_extension = None
    t0 = time.time()

    for parent_index in range(start, end):
        _oi, _local, ext5, P5, complete5, _touched5 = parents[parent_index]
        circuit = circuit_support(complete5, cache)
        circuit_census[len(circuit)] += 1
        pairs = candidate_added_pairs(ext5, circuit)
        raw_pairs += len(pairs)

        for e, f in pairs:
            ext7 = tuple(ext5) + (e, f)
            cand, nspaces, neligible = coefficient_extensions(ext7, P5)
            max_intermediate_spaces = max(max_intermediate_spaces, nspaces)
            max_eligible_blocks = max(max_eligible_blocks, neligible)
            extension_spaces += len(cand)
            if cand and first_extension is None:
                first_extension = {
                    "parent_index": parent_index,
                    "ext5": list(ext5),
                    "added": [e, f],
                    "circuit": list(circuit),
                    "count": len(cand),
                }

    assert extension_spaces == 0, first_extension
    return {
        "start": start,
        "end": end,
        "parents": end - start,
        "raw_pair_candidates": raw_pairs,
        "extension_spaces": extension_spaces,
        "circuit_census": dict(sorted(circuit_census.items())),
        "max_intermediate_spaces": max_intermediate_spaces,
        "max_eligible_blocks": max_eligible_blocks,
        "first_extension": first_extension,
        "seconds": time.time() - t0,
    }


def save_pickle(path, value):
    with open(path, "wb") as f:
        pickle.dump(value, f, protocol=pickle.HIGHEST_PROTOCOL)


def load_pickle(path):
    with open(path, "rb") as f:
        return pickle.load(f)


def write_json(path, value):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(value, f, indent=2, sort_keys=True)
        f.write("\n")


def main():
    parser = ArgumentParser()
    sub = parser.add_subparsers(dest="stage", required=True)

    p = sub.add_parser("five")
    p.add_argument("--start", type=int, default=0)
    p.add_argument("--end", type=int, default=20451)
    p.add_argument("--output", required=True)

    p = sub.add_parser("merge-five")
    p.add_argument("--inputs", nargs="+", required=True)
    p.add_argument("--output", required=True)

    p = sub.add_parser("seven")
    p.add_argument("--input", required=True)
    p.add_argument("--start", type=int, default=0)
    p.add_argument("--end", type=int, default=4717)
    p.add_argument("--output", required=True)

    p = sub.add_parser("merge-seven")
    p.add_argument("--inputs", nargs="+", required=True)

    args = parser.parse_args()

    assert R.lucas_lehmer_127()
    max_complete_norm2 = max(
        sum(x * x for x in row) for row in K2.COMPLETE_T
    )
    assert max_complete_norm2 == 12
    assert R.P * R.P > max_complete_norm2 ** 15

    if args.stage == "five":
        result = scan_five(args.start, args.end)
        save_pickle(args.output, result)
        print("PASS: five-row d=1 shadow shard")
        print("orbit_range", result["start"], result["end"])
        print("d1_parents", len(result["parents"]))
        print("deficiency_census", dict(sorted(result["deficiency_census"].items())))
        print("rank_cache_size", result["rank_cache_size"])
        print("seconds", round(result["seconds"], 3))
        return

    if args.stage == "merge-five":
        shards = [load_pickle(path) for path in args.inputs]
        shards.sort(key=lambda x: x["start"])
        assert shards and shards[0]["start"] == 0
        for a, b in zip(shards, shards[1:]):
            assert a["end"] == b["start"]
        assert shards[-1]["end"] == 20451

        parents = tuple(p for shard in shards for p in shard["parents"])
        deficiency_census = Counter()
        complete_deficiency_census = Counter()
        for shard in shards:
            deficiency_census.update(shard["deficiency_census"])
            complete_deficiency_census.update(shard["complete_deficiency_census"])

        assert deficiency_census.get(0, 0) == 0
        assert len(parents) == 4717
        assert len({p[0] for p in parents}) == 3940
        assert dict(sorted(Counter(len(p[4]) for p in parents).items())) == {
            4: 4026,
            6: 247,
            7: 376,
            8: 20,
            9: 48,
        }

        cache = CompleteRankCache()
        circuit_census = Counter(
            len(circuit_support(p[4], cache)) for p in parents
        )
        assert dict(sorted(circuit_census.items())) == {
            4: 4557,
            6: 157,
            8: 3,
        }

        merged = {
            "start": 0,
            "end": 20451,
            "parents": parents,
            "deficiency_census": deficiency_census,
            "complete_deficiency_census": complete_deficiency_census,
            "circuit_census": circuit_census,
        }
        save_pickle(args.output, merged)
        print("PASS: merged exhaustive five-row d=1 shadows")
        print("d1_parents", len(parents))
        print("orbit_representatives", len({p[0] for p in parents}))
        print("deficiency_zero_states", deficiency_census.get(0, 0))
        print("circuit_census", dict(sorted(circuit_census.items())))
        print("output", args.output)
        return

    if args.stage == "seven":
        merged = load_pickle(args.input)
        result = scan_seven(merged, args.start, args.end)
        write_json(args.output, result)
        print("PASS: seven-row coefficient-extension shard")
        print("parent_range", result["start"], result["end"])
        print("parents", result["parents"])
        print("raw_pair_candidates", result["raw_pair_candidates"])
        print("coefficient_extension_spaces", result["extension_spaces"])
        print("circuit_census", result["circuit_census"])
        print("max_intermediate_spaces", result["max_intermediate_spaces"])
        print("max_eligible_blocks", result["max_eligible_blocks"])
        print("seconds", round(result["seconds"], 3))
        return

    summaries = []
    for path in args.inputs:
        with open(path, "r", encoding="utf-8") as f:
            summaries.append(json.load(f))
    summaries.sort(key=lambda x: x["start"])
    assert summaries and summaries[0]["start"] == 0
    for a, b in zip(summaries, summaries[1:]):
        assert a["end"] == b["start"]
    assert summaries[-1]["end"] == 4717

    total_parents = sum(x["parents"] for x in summaries)
    total_pairs = sum(x["raw_pair_candidates"] for x in summaries)
    total_extensions = sum(x["extension_spaces"] for x in summaries)
    circuit_census = Counter()
    for x in summaries:
        circuit_census.update({int(k): v for k, v in x["circuit_census"].items()})

    assert total_parents == 4717
    assert total_pairs == 531888
    assert total_extensions == 0
    assert dict(sorted(circuit_census.items())) == {4: 4557, 6: 157, 8: 3}

    print("PASS: seven-no-root D=-2,k=4,d=1,p=0 branch closed")
    print("five_row_d1_parents", total_parents)
    print("candidate_added_pairs", total_pairs)
    print("coefficient_extension_spaces", total_extensions)
    print("circuit_census", dict(sorted(circuit_census.items())))
    print("max_complete_row_norm_squared", max_complete_norm2)
    print("hadamard_exact_rank_bound", R.P * R.P > max_complete_norm2 ** 15)


if __name__ == "__main__":
    main()
