#!/usr/bin/env python3
"""Direct source cover for Profile B with minimum coefficient weight >=4.

All 105 local singleton-constraint templates have entries 0,+/-1 and support8.
Empty constraints are also spanned by templates. Any actual rank2 coefficient
plane is therefore generated by two distinct templates restricted to the eight
chosen external cycles. Template labels are (triangle,marked opposite vertex).
Unordered pairs have nine S7 orbits, classified by triangle intersection and
positions/equality of the two marks. The C++ checker enumerates ALL eight-cycle
subsets with minimum restricted-code weight>=4 for each pair representative.

It rejects only virtual deficiency !=3 or singleton capacity <9, using integer
plane membership and Hadamard-certified complete ranks. Surviving sources are
only candidates, not counterexamples or a closure proof. Optional exact
functional ranks use the existing rational row-index implementation.
"""

import argparse
from collections import Counter
import contextlib
import importlib.util
import io
from itertools import combinations
from itertools import permutations
from pathlib import Path
import subprocess
import tempfile
import time

HERE = Path(__file__).resolve().parent


def import_module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    with contextlib.redirect_stdout(io.StringIO()):
        spec.loader.exec_module(module)
    return module


def pair_type(first, second):
    a, x = first
    b, y = second
    common = set(a) & set(b)
    return len(common), int(x in common) + int(y in common), int(x == y)


def support_cover_count(first, second):
    """Count the exact eight-subsets with coefficient minimum weight >=4."""
    from itertools import product
    from math import comb

    directions = Counter()
    for a, b in zip(first, second):
        if a or b:
            key = (1, b / a) if a else (0, 1)
            directions[key] += 1
    outside = len(first) - sum(directions.values())
    result = 0
    for selected in range(6, 9):
        for counts in product(range(selected + 1), repeat=4):
            if sum(counts) != selected or max(counts) > selected - 4:
                continue
            ways = 1
            projective = ((1, 0), (0, 1), (1, 1), (1, -1))
            for direction, number in zip(projective, counts):
                available = directions[direction]
                if number > available:
                    ways = 0
                    break
                ways *= comb(available, number)
            if ways:
                ways *= comb(outside, 8 - selected)
                result += ways
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pair-start', type=int, default=0)
    parser.add_argument('--pair-end', type=int, default=9)
    parser.add_argument('--require-no-survivors', action='store_true')
    args = parser.parse_args()
    start = time.monotonic()
    R = import_module('e99_template_source', HERE /
        'verify_target_c_support7_global_segment_relative_four_noroot_k2_2026_09_20.py')
    complete_t = tuple(tuple(R.MCOORD[R.BLOCKS[b][0]][70+j]
                             - R.MCOORD[R.BLOCKS[b][1]][70+j]
                             - R.MCOORD[R.BLOCKS[b][2]][70+j]
                             for j in range(15)) for b in range(35))
    templates, labels = [], []
    for block, triangle in enumerate(R.BLOCK_LABELS):
        for state, (lx, ly) in enumerate(R.LOCAL):
            templates.append(tuple(lx*R.QCOMP[e][block][1]-ly*R.QCOMP[e][block][0]
                                   for e in R.NO_ROOT))
            desc = R.DESC[R.BLOCKS[block][state]]
            labels.append((triangle, desc[(desc.index(0)+2) % 4]))
    assert len(set(labels)) == 105
    assert all(set(row) <= {-1,0,1} and sum(x != 0 for x in row) == 8
               for row in templates)
    orbits, census = {}, Counter()
    for i, j in combinations(range(105), 2):
        kind = pair_type(labels[i], labels[j])
        orbits.setdefault(kind, (i,j))
        census[kind] += 1
    assert len(orbits) == 9 and sum(census.values()) == 5460
    for kind, representative in orbits.items():
        image_pairs = set()
        for permutation in permutations(range(1, 8)):
            def image(label):
                triangle, marked = label
                return tuple(sorted(permutation[x-1] for x in triangle)), permutation[marked-1]
            pair = tuple(sorted((image(labels[representative[0]]),
                                 image(labels[representative[1]]))))
            image_pairs.add(pair)
        assert len(image_pairs) == census[kind]
    pairs = [orbits[kind] for kind in sorted(orbits)]
    expected_candidates = sum(support_cover_count(templates[a], templates[b])
                              for a, b in pairs)
    assert expected_candidates == 3332125
    print('independent_support_subset_count', expected_candidates, flush=True)
    print('pair_orbits', [(kind, orbits[kind], census[kind]) for kind in sorted(orbits)], flush=True)
    print('import_seconds', time.monotonic()-start, flush=True)
    data = [str(len(pairs))]
    data.extend(' '.join(map(str,row)) for row in templates)
    data.extend(' '.join(str(x) for pair in R.QCOMP[e] for x in pair) for e in R.NO_ROOT)
    data.extend(' '.join(map(str,row)) for row in complete_t)
    data.extend(f'{i} {j}' for i,j in pairs)
    input_data = '\n'.join(data)+'\n'
    counts = Counter()
    with tempfile.TemporaryDirectory(prefix='e99-template-cover-') as directory:
        binary = Path(directory)/'cover'
        subprocess.run(['g++','-std=c++17','-O3','-Wall','-Wextra',
                        str(HERE/'target_c_profile_b_template_cover.cpp'),'-o',str(binary)],check=True)
        # Communicate avoids deadlock if the scan emits many candidates.
        result = subprocess.run([str(binary),str(args.pair_start),str(args.pair_end)],
                                input=input_data,text=True,capture_output=True,check=True)
        exact_d3_checks = 0
        for line in result.stdout.splitlines():
            if line.startswith('D3EXAMPLE '):
                values = list(map(int, line.split()[1:]))
                _pair, a, b, *rest = values
                indices, capacity, complete_count = rest[:8], rest[8], rest[9]
                ext = tuple(R.NO_ROOT[i] for i in indices)
                space = R.rowspace_key(tuple(tuple(templates[j][i] for i in indices)
                                             for j in (a,b)))
                assert len(space)==2
                # Direct rational code-weight check via all 3-coordinate deletions.
                for deleted in combinations(range(8),3):
                    kept = tuple(i for i in range(8) if i not in deleted)
                    projected = tuple(tuple(row[i] for i in kept) for row in space)
                    assert len(R.rowspace_key(projected))==2
                touched = tuple(b for b in range(35)
                                if any(R.QCOMP[e][b] != (0,0) for e in ext))
                complete = tuple(b for b in touched
                                 if not R.is_subspace(R.local_constraint_key(ext,b,0),space))
                assert len(complete)==complete_count
                exact_deficiency = len(complete)-R.exact_rank([complete_t[x] for x in complete])
                assert exact_deficiency==3
                good = tuple(block for block in complete if any(
                    R.is_subspace(R.local_constraint_key(ext,block,state),space)
                    for state in (1,2,4)))
                assert len(good)==capacity and capacity<9
                exact_d3_checks += 1
                continue
            if not line.startswith('SURVIVOR '):
                print(line, flush=True)
                continue
            values = list(map(int,line.split()[1:]))
            a,b,*rest = values
            indices, capacity, complete_count = rest[:8],rest[8],rest[9]
            counts['structural_survivors'] += 1
            print(line,flush=True)
        print('structural_counts',dict(counts),'exact_rational_d3_examples',exact_d3_checks,flush=True)
    if args.require_no_survivors:
        assert not counts['structural_survivors']
    print('PASS: requested template-pair cover completed; seconds',time.monotonic()-start)


if __name__ == '__main__':
    main()