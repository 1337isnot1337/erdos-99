#!/usr/bin/env python3
"""Actual-state realization audit for eight-no-root k=6 Profile B.

This strengthens the fixed-nine-block Profile B audit. A genuine Profile B
state does not merely have nine singleton replacement classes forming a
functional basis through the clean puncture fan. Those same nine singleton
block states, together with the unchanged canonical-empty blocks, must generate
exactly the prescribed rank-two coefficient-constraint plane.

For a fixed eight-row virtual state let E be the constraint span supplied by
canonical-empty blocks. Every compatible singleton block b contributes a
constraint space L_b of dimension at most one inside the prescribed plane P.
Because dim(P)=2, a functional-basis realization exists only if an independent
set of at most two compatible singleton classes already completes E to P.
Conversely, such an independent seed extends to a nine-element functional
basis because the compatible singleton classes span functional rank nine.

The six-row audit supplies more structure: a genuine source must extend one of
the exact common seven-block bases selected at the synchronized six-row seed.
This wrapper carries those basis identities through the two-row lift and
requires the chosen global nine-set to contain one such seven-block seed.

The wrapper also monkeypatches the fixed-nine exact rank test so that the same
chosen nine blocks must actually generate P. For every passing chosen set it
reconstructs the actual root-block state and independently checks its exact
rational relation defect is -1.
"""

from collections import Counter
from itertools import combinations
from pathlib import Path
import contextlib
import importlib.util
import io

HERE = Path(__file__).resolve().parent
BASE = HERE / "verify_target_c_support7_global_segment_relative_eight_noroot_k6_dminus1_profile_b_fixed_nine_basis_2026_09_22.py"
spec = importlib.util.spec_from_file_location("e99_profile_b_fixed_nine", BASE)
F = importlib.util.module_from_spec(spec)
with contextlib.redirect_stdout(io.StringIO()):
    spec.loader.exec_module(F)

L = F.L
B = F.B
C = F.C
R = F.R
S = F.S
G = F.G
P0 = F.P0

ORIG_FIXED_NINE_BASIS_EXISTS = F.fixed_nine_basis_exists
ORIG_FIXED_EXTRA_RANK = F.fixed_extra_rank
ORIG_GLOBAL_LIFT_COMMON_BASIS = B.common_basis_block_sets

ACTUAL_COUNTS = Counter()
ACTUAL_EXAMPLES = []
CURRENT_SEED_CONTEXT = None
CURRENT_SOURCE_SEEDS = ()


def actual_space(ext, touched, states):
    """Exact coefficient plane generated by the specified actual block states."""
    space = ()
    for block, state in zip(touched, states):
        space = R.union_key(space, R.local_constraint_key(ext, block, state))
        if len(space) > 2:
            return space
    return space


def source_data(ext8, space8, rank_cache):
    """Canonical source quotient, compatible singleton classes, and E <= P."""
    state8 = F.canonical_state(ext8, space8, rank_cache)
    if state8 is None:
        return None
    complete, d8, _rows, canonical, base_rank = state8
    if d8 != 3:
        return None

    touched = S.touched_blocks(ext8)
    virtual_states = G.virtual_canonical(ext8, touched, space8)
    complete_index = {block: i for i, block in enumerate(complete)}

    singleton_state = {}
    singleton_vector = {}
    singleton_constraint = {}
    for block in complete:
        options = B.singleton_options(ext8, block, space8)
        if not options:
            continue
        assert len(options) == 1
        state = options[0]
        constraint = R.local_constraint_key(ext8, block, state)
        assert R.is_subspace(constraint, space8)
        singleton_state[block] = state
        singleton_constraint[block] = constraint
        singleton_vector[block] = B.replacement_functional(
            ext8,
            block,
            state,
            space8,
            complete_index,
            len(complete),
        )

    empty_space = ()
    for block, state in zip(touched, virtual_states):
        if state != 0:
            continue
        empty_space = R.union_key(
            empty_space, R.local_constraint_key(ext8, block, 0)
        )
    assert R.is_subspace(empty_space, space8)

    return {
        "touched": touched,
        "virtual_states": virtual_states,
        "canonical": canonical,
        "base_rank": base_rank,
        "state": singleton_state,
        "vector": singleton_vector,
        "constraint": singleton_constraint,
        "empty_space": empty_space,
    }


def extra_rank(data, blocks):
    return (
        C.rank_q(data["canonical"] + [data["vector"][b] for b in blocks])
        - data["base_rank"]
    )


def independent_coefficient_seed_exists(ext8, space8, rank_cache):
    """Rank-two seed lemma prefilter for an actual nine-singleton basis."""
    data = source_data(ext8, space8, rank_cache)
    if data is None:
        return False
    good = tuple(data["vector"])
    if len(good) < 9:
        return False
    if extra_rank(data, good) != 9:
        return False

    E = data["empty_space"]
    ACTUAL_COUNTS[("empty_constraint_rank", len(E))] += 1
    ACTUAL_COUNTS[("source_singleton_capacity", len(good))] += 1

    for size in range(3):
        for seed in combinations(good, size):
            coeff = E
            for block in seed:
                coeff = R.union_key(coeff, data["constraint"][block])
            if coeff != space8:
                continue
            if extra_rank(data, seed) != size:
                continue
            ACTUAL_COUNTS[("independent_coefficient_seed_size", size)] += 1
            return True

    ACTUAL_COUNTS["no_independent_coefficient_seed"] += 1
    return False


def source_extending_six_basis_sets(ext8, space8, rank_cache):
    """Common six-row bases that extend to a source-level nine-block basis.

    The current six-row scan supplies exact seven-block bases whose singleton
    classes span the six-row quotient and all of its required punctures. Their
    source classes must therefore remain independent. A genuine global source
    adds exactly two singleton blocks. We retain a seed only if two source
    singleton classes raise functional rank from seven to nine and, together
    with the seed constraints and canonical-empty constraints, generate P_8.
    """
    if CURRENT_SEED_CONTEXT is None:
        return ()
    ext6, space6, seed_sets = CURRENT_SEED_CONTEXT
    data = source_data(ext8, space8, rank_cache)
    if data is None:
        return ()

    out = []
    for seed in seed_sets:
        seed = tuple(seed)
        if len(seed) != 7 or len(set(seed)) != 7:
            continue

        compatible = True
        for block in seed:
            source_state = data["state"].get(block)
            if source_state is None:
                compatible = False
                break
            options6 = B.singleton_options(ext6, block, space6)
            if len(options6) != 1 or options6[0] != source_state:
                compatible = False
                break
        if not compatible:
            continue

        if extra_rank(data, seed) != 7:
            ACTUAL_COUNTS["six_basis_not_independent_at_source"] += 1
            continue

        coeff_base = data["empty_space"]
        for block in seed:
            coeff_base = R.union_key(coeff_base, data["constraint"][block])
        ACTUAL_COUNTS[("six_basis_source_coefficient_rank", len(coeff_base))] += 1

        seed_set = set(seed)
        extras = tuple(block for block in data["vector"] if block not in seed_set)
        extends = False
        for x, y in combinations(extras, 2):
            chosen = seed + (x, y)
            if extra_rank(data, chosen) != 9:
                continue
            coeff = R.union_key(
                R.union_key(coeff_base, data["constraint"][x]),
                data["constraint"][y],
            )
            if coeff != space8:
                continue
            extends = True
            break
        if extends:
            out.append(seed)

    if out:
        ACTUAL_COUNTS["six_basis_source_extension_candidates"] += len(out)
    else:
        ACTUAL_COUNTS["no_six_basis_source_extension"] += 1
    return tuple(out)


def fixed_nine_basis_exists_with_source_prefilter(ext8, space8, rank_cache):
    global CURRENT_SOURCE_SEEDS
    ACTUAL_COUNTS["fixed_nine_source_candidates"] += 1
    CURRENT_SOURCE_SEEDS = ()
    if not independent_coefficient_seed_exists(ext8, space8, rank_cache):
        return False
    ACTUAL_COUNTS["source_seed_survivors"] += 1

    seeds = source_extending_six_basis_sets(ext8, space8, rank_cache)
    if not seeds:
        return False
    ACTUAL_COUNTS["source_six_basis_survivors"] += 1
    CURRENT_SOURCE_SEEDS = seeds
    try:
        return ORIG_FIXED_NINE_BASIS_EXISTS(ext8, space8, rank_cache)
    finally:
        CURRENT_SOURCE_SEEDS = ()


def fixed_extra_rank_with_actual_state(ext, space, state_data, block_states):
    """Require the chosen source nine-set to extend a fixed six-row basis."""
    if len(ext) == 8 and len(block_states) == 9:
        chosen_blocks = {block for block, _state in block_states}
        if not any(set(seed).issubset(chosen_blocks) for seed in CURRENT_SOURCE_SEEDS):
            ACTUAL_COUNTS["chosen_nine_misses_all_six_bases"] += 1
            return -1
        ACTUAL_COUNTS["chosen_nine_extends_six_basis"] += 1

        touched = S.touched_blocks(ext)
        virtual_states = G.virtual_canonical(ext, touched, space)
        position = {block: i for i, block in enumerate(touched)}
        actual_states = list(virtual_states)

        for block, state in block_states:
            if block not in position:
                return -1
            # The fixed-nine caller chooses only source-compatible complete
            # blocks. Recheck rather than relying on that implementation detail.
            if virtual_states[position[block]] != 7:
                return -1
            options = B.singleton_options(ext, block, space)
            if len(options) != 1 or options[0] != state:
                return -1
            actual_states[position[block]] = state

        generated = actual_space(ext, touched, tuple(actual_states))
        if generated != space:
            ACTUAL_COUNTS["chosen_nine_wrong_coefficient_space"] += 1
            return -1
        ACTUAL_COUNTS["chosen_nine_realizes_coefficient_space"] += 1

        rank = ORIG_FIXED_EXTRA_RANK(ext, space, state_data, block_states)
        if rank != 9:
            return rank

        incomplete_cost = sum(
            R.STATES[state][1]
            for state in actual_states
            if state != 7
        )
        if incomplete_cost != 9:
            ACTUAL_COUNTS["chosen_nine_wrong_incomplete_cost"] += 1
            return -1

        # Independent audit: build the actual relation matrix, not the
        # canonical matrix plus abstract functionals, and recover D=-1 exactly.
        actual_rows = L.generic_relation_rows(
            ext, touched, tuple(actual_states), space
        )
        actual_relation_rank = C.rank_q(actual_rows)
        nrows = len(ext) + sum(R.STATES[state][1] for state in actual_states)
        defect = nrows - 3 * actual_relation_rank
        if defect != -1:
            ACTUAL_COUNTS["chosen_nine_wrong_exact_defect"] += 1
            return -1
        ACTUAL_COUNTS["chosen_nine_exact_defect_minus1"] += 1

        if len(ACTUAL_EXAMPLES) < 20:
            ACTUAL_EXAMPLES.append(
                (
                    tuple(ext),
                    space,
                    tuple(block_states),
                    tuple(actual_states),
                    actual_relation_rank,
                )
            )
        return rank

    return ORIG_FIXED_EXTRA_RANK(ext, space, state_data, block_states)


def global_lift_common_basis_with_seed(good6, projected_complete, projected_data):
    """Carry the exact six-row common-basis identities into the global lift."""
    global CURRENT_SEED_CONTEXT
    candidates = L.ORIG_STRONG_COMMON_BASIS(
        good6, projected_complete, projected_data
    )
    if not candidates:
        return ()

    assert L.C.CURRENT_SIX is not None
    ext6, space6, _complete6, recorded_good6 = L.C.CURRENT_SIX
    assert tuple(good6) == recorded_good6

    previous = CURRENT_SEED_CONTEXT
    CURRENT_SEED_CONTEXT = (
        tuple(ext6),
        space6,
        tuple(tuple(blocks) for blocks in candidates),
    )
    try:
        if not L.has_global_profile_b_lift(ext6, space6):
            return ()
        return candidates
    finally:
        CURRENT_SEED_CONTEXT = previous


# The fixed-nine global checker resolves these module globals at call time.
