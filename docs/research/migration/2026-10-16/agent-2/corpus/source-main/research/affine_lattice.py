"""Exact affine-lattice regression for the triangle-free near-hexagonal phase.

For 0 < epsilon < 1, take basis vectors u and v with

    |u| = 1,
    |v| = 1 + epsilon,
    angle(u, v) = 60 degrees.

The lattice then has minimum distance one, but its unit-distance graph consists
only of parallel u-edges, so it contains no unit equilateral triangle.  The
fundamental area tends to the hexagonal optimum as epsilon tends to zero.

Squared distances are kept as exact rational numbers.  This makes the finite
regression independent of floating-point tolerance and records the precise
boundary-scale loophole in a density-only proof.
"""

from __future__ import annotations

from dataclasses import dataclass
from fractions import Fraction
from typing import Iterable


Index = tuple[int, int]


@dataclass(frozen=True)
class AffineLattice:
    """The lattice generated by u=(1,0) and v at 60 degrees with length 1+epsilon."""

    epsilon: Fraction

    def __post_init__(self) -> None:
        if not (Fraction(0) < self.epsilon < Fraction(1)):
            raise ValueError("epsilon must lie strictly between zero and one")

    @property
    def scale(self) -> Fraction:
        return Fraction(1) + self.epsilon

    @property
    def determinant_ratio_to_hexagonal(self) -> Fraction:
        """Fundamental area divided by sqrt(3)/2."""

        return self.scale

    def squared_norm(self, index: Index) -> Fraction:
        """Squared Euclidean norm of index[0] * u + index[1] * v."""

        a, b = index
        s = self.scale
        return Fraction(a * a) + s * a * b + s * s * b * b

    def squared_distance(self, first: Index, second: Index) -> Fraction:
        return self.squared_norm((first[0] - second[0], first[1] - second[1]))

    def patch(self, side: int) -> tuple[Index, ...]:
        if side < 1:
            raise ValueError("side must be positive")
        return tuple((i, j) for i in range(side) for j in range(side))

    def patch_squared_diameter(self, side: int) -> Fraction:
        """Squared diameter of the axis-aligned side-by-side patch."""

        if side < 1:
            raise ValueError("side must be positive")
        span = side - 1
        s = self.scale
        return Fraction(span * span) * (1 + s + s * s)

    def unit_difference_indices(self, bound: int) -> tuple[Index, ...]:
        """Enumerate nonzero bounded differences having squared norm one."""

        if bound < 1:
            raise ValueError("bound must be positive")
        return tuple(
            (a, b)
            for a in range(-bound, bound + 1)
            for b in range(-bound, bound + 1)
            if (a, b) != (0, 0) and self.squared_norm((a, b)) == 1
        )

    def verify_patch(self, side: int) -> dict[str, Fraction | int | bool]:
        """Return exact minimum-distance and no-unit-triangle checks."""

        points = self.patch(side)
        differences = [
            self.squared_distance(first, second)
            for position, first in enumerate(points)
            for second in points[position + 1 :]
        ]
        minimum = min(differences) if differences else Fraction(0)
        unit_differences = self.unit_difference_indices(max(1, side - 1))
        return {
            "points": len(points),
            "minimum_squared_distance": minimum,
            "minimum_distance_is_one": minimum == 1 if differences else True,
            "unit_difference_count": len(unit_differences),
            "unit_differences_are_horizontal": all(
                b == 0 and abs(a) == 1 for a, b in unit_differences
            ),
            "triangle_free": len(unit_differences) == 2,
            "diameter_squared": self.patch_squared_diameter(side),
        }


def near_hexagonal_family(
    epsilons: Iterable[Fraction], side: int
) -> tuple[dict[str, Fraction | int | bool], ...]:
    """Evaluate a finite list of exact affine-lattice regressions."""

    return tuple(
        AffineLattice(epsilon).verify_patch(side) for epsilon in epsilons
    )


if __name__ == "__main__":
    for epsilon in (Fraction(1, 10), Fraction(1, 100), Fraction(1, 1000)):
        lattice = AffineLattice(epsilon)
        print(
            f"epsilon={epsilon} determinant_ratio={lattice.determinant_ratio_to_hexagonal} "
            f"side=32 summary={lattice.verify_patch(32)}"
        )
